// GlyphMask représente un masque alpha 8-bit d'un glyphe avec ses métadonnées géométriques.
type GlyphMask struct {
	Width    int
	Height   int
	Stride   int
	AdvanceX int
	OffsetY  int
	Mask     []byte
}

// FontManager gère la rastérisation et la mise en cache des glyphes typographiques.
type FontManager struct {
	mu         sync.RWMutex
	ttFont     *tt55.Tt55_font
	hasTT      bool
	glyphCache map[uint64]*GlyphMask // Clé: (codepoint << 16) | (size & 0xFFFF)
}

var (
	defaultFontManager     *FontManager
	defaultFontManagerOnce sync.Once
)

// DefaultFontManager retourne l'instance partagée du gestionnaire de polices.
func DefaultFontManager() *FontManager {
	defaultFontManagerOnce.Do(func() {
		defaultFontManager = &FontManager{
			glyphCache: make(map[uint64]*GlyphMask),
		}
	})
	return defaultFontManager
}

// SetTTFont configure la police TrueType active pour le gestionnaire.
func (fm *FontManager) SetTTFont(font *tt55.Tt55_font) {
	fm.mu.Lock()
	defer fm.mu.Unlock()
	fm.ttFont = font
	fm.hasTT = font != nil
	fm.glyphCache = make(map[uint64]*GlyphMask)
}

// GetGlyphMask retourne le masque alpha 8-bit pour un point de code et une taille donnés.
func (fm *FontManager) GetGlyphMask(cp rune, size int) *GlyphMask {
	if size <= 0 {
		size = 14
	}

	key := (uint64(cp) << 16) | (uint64(size) & 0xFFFF)

	fm.mu.RLock()
	mask, ok := fm.glyphCache[key]
	fm.mu.RUnlock()
	if ok {
		return mask
	}

	fm.mu.Lock()
	defer fm.mu.Unlock()
	if mask, ok := fm.glyphCache[key]; ok {
		return mask
	}

	mask = fm.rasterizeGlyph(cp, size)
	fm.glyphCache[key] = mask
	return mask
}

// rasterizeGlyph produit un masque alpha 8-bit pour un caractère à la taille demandée.
func (fm *FontManager) rasterizeGlyph(cp rune, size int) *GlyphMask {
	// Échelle de base: matrice 8x16 mise à l'échelle avec interpolation sous-pixel
	scale := float64(size) / 16.0
	if scale < 0.5 {
		scale = 0.5
	}

	w := int(float64(8)*scale + 0.5)
	h := int(float64(16)*scale + 0.5)
	if w < 1 {
		w = 1
	}
	if h < 1 {
		h = 1
	}

	stride := w
	mask := make([]byte, w*h)

	// Caractère espace
	if cp == ' ' {
		spaceAdv := w
		if fm.hasTT && fm.ttFont != nil && fm.ttFont.Units_per_em > 0 {
			var gid, aw uint16
			if tt55.Tt55_glyph(fm.ttFont, ' ', &gid) == 0 && tt55.Tt55_advance(fm.ttFont, gid, &aw) == 0 {
				spaceAdv = int(float64(aw)*float64(size)/float64(fm.ttFont.Units_per_em) + 0.5)
			}
		}
		return &GlyphMask{
			Width:    w,
			Height:   h,
			Stride:   stride,
			AdvanceX: spaceAdv,
			OffsetY:  0,
			Mask:     mask,
		}
	}

	// Récupération de l'avance métrique via tt55 si disponible
	advanceX := w + 1
	if fm.hasTT && fm.ttFont != nil && fm.ttFont.Units_per_em > 0 {
		var gid, aw uint16
		if tt55.Tt55_glyph(fm.ttFont, uint32(cp), &gid) == 0 && gid > 0 {
			if tt55.Tt55_advance(fm.ttFont, gid, &aw) == 0 && aw > 0 {
				advanceX = int(float64(aw)*float64(size)/float64(fm.ttFont.Units_per_em) + 0.5)
			}
		}
	}

	// Récupération de la matrice bitmap de base (8x16)
	baseBitmap := get8x16Bitmap(cp)

	// Échantillonnage avec anti-aliasing bilinéaire pour un rendu typographique lisse
	for dy := 0; dy < h; dy++ {
		srcY := float64(dy) / scale
		sy0 := int(srcY)
		sy1 := sy0 + 1
		fy := srcY - float64(sy0)
		if sy0 >= 16 {
			sy0 = 15
		}
		if sy1 >= 16 {
			sy1 = 15
		}

		for dx := 0; dx < w; dx++ {
			srcX := float64(dx) / scale
			sx0 := int(srcX)
			sx1 := sx0 + 1
			fx := srcX - float64(sx0)
			if sx0 >= 8 {
				sx0 = 7
			}
			if sx1 >= 8 {
				sx1 = 7
			}

			// 4 échantillons
			v00 := float64(getBit(baseBitmap, sx0, sy0)) * 255.0
			v10 := float64(getBit(baseBitmap, sx1, sy0)) * 255.0
			v01 := float64(getBit(baseBitmap, sx0, sy1)) * 255.0
			v11 := float64(getBit(baseBitmap, sx1, sy1)) * 255.0

			val := (1.0-fx)*(1.0-fy)*v00 + fx*(1.0-fy)*v10 + (1.0-fx)*fy*v01 + fx*fy*v11
			if val > 255.0 {
				val = 255.0
			} else if val < 0.0 {
				val = 0.0
			}

			mask[dy*stride+dx] = uint8(val)
		}
	}

	return &GlyphMask{
		Width:    w,
		Height:   h,
		Stride:   stride,
		AdvanceX: advanceX,
		OffsetY:  0,
		Mask:     mask,
	}
}

func getBit(bitmap [16]uint8, x, y int) uint8 {
	if y < 0 || y >= 16 || x < 0 || x >= 8 {
		return 0
	}
	row := bitmap[y]
	if (row & (1 << (7 - x))) != 0 {
		return 1
	}
	return 0
}

// MeasureString calcule la largeur et hauteur en pixels d'une chaîne de texte.
func MeasureString(text string, size int) (int, int) {
	if text == "" {
		return 0, size
	}
	fm := DefaultFontManager()
	width := 0
	height := size

	for _, cp := range text {
		gm := fm.GetGlyphMask(cp, size)
		if gm != nil {
			width += gm.AdvanceX
			if gm.Height > height {
				height = gm.Height
			}
		}
	}
	return width, height
}

// DrawString trace une chaîne de texte sur le peintre c2painter aux coordonnées (x, y).
func DrawString(p *c2painter.Painter, text string, x, y int, size int, color uint32) {
	if text == "" || p == nil {
		return
	}
	fm := DefaultFontManager()
	curX := x

	for _, cp := range text {
		gm := fm.GetGlyphMask(cp, size)
		if gm != nil {
			if len(gm.Mask) > 0 && cp != ' ' {
				p.DrawTextGlyph(curX, y+gm.OffsetY, gm.Width, gm.Height, gm.Mask, gm.Stride, color)
			}
			curX += gm.AdvanceX
		}
	}
}

// get8x16Bitmap extrait la matrice binaire 8x16 d'un glyphe (ASCII étendu et symboles).
func get8x16Bitmap(cp rune) [16]uint8 {
	if cp >= 0 && cp < 128 {
		return ascii8x16[cp]
	}

	// Caractères accentués français courants
	switch cp {
	case 'é':
		b := ascii8x16['e']
		b[0] = 0x08
		b[1] = 0x10
		return b
	case 'è':
		b := ascii8x16['e']
		b[0] = 0x10
		b[1] = 0x08
		return b
	case 'ê':
		b := ascii8x16['e']
		b[0] = 0x10
		b[1] = 0x28
		return b
	case 'à':
		b := ascii8x16['a']
		b[0] = 0x10
		b[1] = 0x08
		return b
	case 'â':
		b := ascii8x16['a']
		b[0] = 0x10
		b[1] = 0x28
		return b
	case 'ô':
		b := ascii8x16['o']
		b[0] = 0x10
		b[1] = 0x28
		return b
	case 'î':
		b := ascii8x16['i']
		b[0] = 0x10
		b[1] = 0x28
		return b
	case 'ç':
		b := ascii8x16['c']
		b[14] = 0x08
		b[15] = 0x10
		return b
	case 'É':
		b := ascii8x16['E']
		b[0] = 0x08
		b[1] = 0x10
		return b
	case 'È':
		b := ascii8x16['E']
		b[0] = 0x10
		b[1] = 0x08
		return b
	case 'À':
		b := ascii8x16['A']
		b[0] = 0x10
		b[1] = 0x08
		return b
	case '•':
		return [16]uint8{0, 0, 0, 0, 0, 0, 0x18, 0x3C, 0x3C, 0x18, 0, 0, 0, 0, 0, 0}
	case '✓':
		return [16]uint8{0, 0, 0, 0, 0, 0x01, 0x03, 0x06, 0x8C, 0xD8, 0x70, 0x20, 0, 0, 0, 0}
	case '▶':
		return [16]uint8{0, 0, 0, 0x80, 0xC0, 0xE0, 0xF0, 0xF8, 0xF8, 0xF0, 0xE0, 0xC0, 0x80, 0, 0, 0}
	case '⚡':
		return [16]uint8{0, 0, 0x08, 0x18, 0x38, 0x78, 0xFC, 0x3E, 0x1C, 0x38, 0x30, 0x20, 0, 0, 0, 0}
	}

	// Caractère de substitution (carré)
	return [16]uint8{
		0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x42,
		0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00, 0x00,
	}
}

