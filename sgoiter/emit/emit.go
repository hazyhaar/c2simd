// formatImm prints integer immediates idiomatic for Go crypto/bit code.
// Small counters stay decimal; masks and large constants → hex; printable bytes → 'c'.
func formatImm(imm int64, ctx ir.TypeName) string {
	switch ctx {
	case ir.TypFloat64:
		f := math.Float64frombits(uint64(imm))
		if math.IsNaN(f) {
			return "math.NaN()"
		}
		if math.IsInf(f, 1) {
			return "math.Inf(1)"
		}
		if math.IsInf(f, -1) {
			return "math.Inf(-1)"
		}
		return fmt.Sprintf("float64(%g)", f)
	case ir.TypFloat32:
		f := math.Float32frombits(uint32(imm))
		f64 := float64(f)
		if math.IsNaN(f64) {
			return "float32(math.NaN())"
		}
		if math.IsInf(f64, 1) {
			return "float32(math.Inf(1))"
		}
		if math.IsInf(f64, -1) {
			return "float32(math.Inf(-1))"
		}
		return fmt.Sprintf("float32(%g)", f)
	case ir.TypUint64:
		u := uint64(imm)
		if preferHexU(u) {
			return fmt.Sprintf("uint64(0x%x)", u)
		}
		return fmt.Sprintf("uint64(%d)", u)
	case ir.TypUint32:
		u := uint32(imm)
		if preferHexU(uint64(u)) {
			return fmt.Sprintf("uint32(0x%x)", u)
		}
		return fmt.Sprintf("uint32(%d)", u)
	case ir.TypUint8:
		u := uint8(imm)
		if preferHexU(uint64(u)) {
			return fmt.Sprintf("uint8(0x%x)", u)
		}
		return fmt.Sprintf("uint8(%d)", u)
	case ir.TypInt8:
		// C (i8)-1 arrives as Imm all-bits; truncate then print signed
		v := int8(imm)
		return fmt.Sprintf("int8(%d)", v)
	case ir.TypInt16:
		v := int16(imm)
		return fmt.Sprintf("int16(%d)", v)
	case ir.TypInt32:
		v := int32(imm)
		if v < 0 {
			return fmt.Sprintf("int32(%d)", v)
		}
		u := uint32(imm)
		if preferHexU(uint64(u)) && u > 255 {
			if u > math.MaxInt32 {
				return fmt.Sprintf("int32(%d)", v)
			}
			return fmt.Sprintf("int32(0x%x)", u)
		}
		return fmt.Sprintf("int32(%d)", v)
	case ir.TypInt64:
		if imm < 0 {
			return fmt.Sprintf("int64(%d)", imm)
		}
		u := uint64(imm)
		if preferHexU(u) && u > 255 {
			return fmt.Sprintf("int64(0x%x)", u)
		}
		return fmt.Sprintf("int64(%d)", imm)
	case "", ir.TypInt:
		if imm < 0 {
			return fmt.Sprintf("%d", imm)
		}
		u := uint64(imm)
		if preferHexU(u) && u > 255 {
			return fmt.Sprintf("0x%x", u)
		}
		return fmt.Sprintf("%d", imm)
	default:
		gt := goType(ctx)
		if gt == "" {
			gt = "int"
		}
		u := uint64(imm)
		if preferHexU(u) {
			return fmt.Sprintf("%s(0x%x)", gt, u)
		}
		return fmt.Sprintf("%s(%d)", gt, imm)
	}
}

func preferHexU(u uint64) bool {
	if u <= 9 {
		return false
	}
	// shift amounts and small counts stay decimal
	if u <= 64 {
		return false
	}
	return true
}

func formatInitCSV(csv string, elem ir.TypeName) string {
	parts := strings.Split(csv, ",")
	var out []string
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		if strings.HasPrefix(p, "0x") || strings.HasPrefix(p, "0X") {
			if u, err := strconv.ParseUint(p[2:], 16, 64); err == nil {
				if u > 9 {
					out = append(out, fmt.Sprintf("0x%x", u))
				} else {
					out = append(out, fmt.Sprintf("%d", u))
				}
				continue
			}
		}
		if d, err := strconv.ParseInt(p, 10, 64); err == nil {
			out = append(out, fmt.Sprintf("%d", d))
			continue
		}
		out = append(out, p)
	}
	return strings.Join(out, ", ")
}

// doWhileOnce: cond is compile-time false after optional const prep (while(0)).
func doWhileOnce(e *env, s ir.Stmt) bool {
	imm := map[ir.Value]int64{}
	for k, v := range e.constImm {
		imm[k] = v
	}
	for _, ins := range s.ForInit {
		if ins.Op == ir.OpConst {
			imm[ins.Dst] = ins.Imm
		}
	}
	switch s.CondOp {
	case "!=", "==":
		l, okL := imm[s.CondLeft]
		r, okR := imm[s.CondRight]
		if !okL || !okR {
			// bare 0 literals sometimes still in constImm only on one side
			return false
		}
		if s.CondOp == "!=" {
			return l == r // 0!=0 → false → exit after one body
		}
		return l != r
	case "truthy", "":
		if l, ok := imm[s.CondLeft]; ok {
			return l == 0
		}
	}
	return false
}

func countUses(ss []ir.Stmt, uc map[ir.Value]int) {
	var walk func([]ir.Stmt)
	walk = func(sts []ir.Stmt) {
		for _, s := range sts {
			bump := func(ins ir.Instr) {
				for _, a := range ins.Args {
					uc[a]++
				}
			}
			for _, ins := range s.ForInit {
				bump(ins)
			}
			for _, ins := range s.ForCondPrep {
				bump(ins)
			}
			for _, ins := range s.ForPost {
				bump(ins)
			}
			for _, ins := range s.SwitchPrep {
				bump(ins)
			}
			if s.CondOp != "" {
				uc[s.CondLeft]++
				uc[s.CondRight]++
			} else if s.Kind == ir.SKIf || s.Kind == ir.SKFor || s.Kind == ir.SKDoWhile {
				if s.CondLeft != ir.NoVal {
					uc[s.CondLeft]++
				}
			}
			if s.Kind == ir.SKSwitch && s.SwitchOn != ir.NoVal {
				uc[s.SwitchOn]++
			}
			if s.Kind == ir.SKInstr {
				bump(s.Ins)
			}
			walk(s.ForBody)
			walk(s.ThenBody)
			walk(s.ElseBody)
			walk(s.DoBody)
			for _, c := range s.SwitchCases {
				walk(c.Body)
			}
		}
	}
	walk(ss)
}

func countWrites(ss []ir.Stmt, wc map[ir.Value]int) {
	var walk func([]ir.Stmt)
	walk = func(sts []ir.Stmt) {
		for _, s := range sts {
			bumpD := func(ins ir.Instr) {
				switch ins.Op {
				case ir.OpNop, ir.OpReturn, ir.OpStore:
					return
				}
				wc[ins.Dst]++
			}
			for _, ins := range s.ForInit {
				bumpD(ins)
			}
			for _, ins := range s.ForCondPrep {
				bumpD(ins)
			}
			for _, ins := range s.ForPost {
				bumpD(ins)
			}
			for _, ins := range s.SwitchPrep {
				bumpD(ins)
			}
			if s.Kind == ir.SKInstr {
				bumpD(s.Ins)
			}
			walk(s.ForBody)
			walk(s.ThenBody)
			walk(s.ElseBody)
			walk(s.DoBody)
			for _, c := range s.SwitchCases {
				walk(c.Body)
			}
		}
	}
	walk(ss)
}

func markDivMulFolds(ss []ir.Stmt, e *env) {
	divs := map[ir.Value]divRec{}
	imm := map[ir.Value]int64{}
	var walk func([]ir.Stmt)
	walk = func(sts []ir.Stmt) {
		for _, s := range sts {
			handle := func(ins ir.Instr) {
				if ins.Op == ir.OpConst {
					imm[ins.Dst] = ins.Imm
					e.foldImm[ins.Dst] = ins.Imm
				}
				// Mov propagates const (offSlot=0, rules copy off+0 → Mov)
				if ins.Op == ir.OpMov && len(ins.Args) == 1 {
					if k, ok := imm[ins.Args[0]]; ok {
						imm[ins.Dst] = k
						e.foldImm[ins.Dst] = k
					} else {
						delete(imm, ins.Dst)
						delete(e.foldImm, ins.Dst)
					}
				}
				if ins.Op == ir.OpDiv && len(ins.Args) == 2 {
					if k, ok := imm[ins.Args[1]]; ok && k > 1 {
						divs[ins.Dst] = divRec{src: ins.Args[0], k: k}
						e.divInfo[ins.Dst] = divs[ins.Dst]
					}
				}
				if ins.Op == ir.OpMul && len(ins.Args) == 2 {
					try := func(quot, kreg ir.Value) {
						if di, ok := divs[quot]; ok {
							if k, ok := imm[kreg]; ok && k == di.k && k > 1 && k&(k-1) == 0 {
								if e.useCount[quot] == 1 {
									e.suppress[quot] = true
								}
							}
						}
					}
					try(ins.Args[0], ins.Args[1])
					try(ins.Args[1], ins.Args[0])
				}
				// offSlot bump kills const-zero
				if ins.Op == ir.OpAdd || ins.Op == ir.OpSub {
					if ins.Sym == "offslot" || ins.Elem == ir.TypUint64 {
						delete(imm, ins.Dst)
						delete(e.foldImm, ins.Dst)
					}
				}
			}
			for _, ins := range s.ForInit {
				handle(ins)
			}
			for _, ins := range s.ForCondPrep {
				handle(ins)
			}
			for _, ins := range s.ForPost {
				handle(ins)
			}
			for _, ins := range s.SwitchPrep {
				handle(ins)
			}
			if s.Kind == ir.SKInstr {
				handle(s.Ins)
			}
			walk(s.ForBody)
			walk(s.ThenBody)
			walk(s.ElseBody)
			walk(s.DoBody)
			for _, c := range s.SwitchCases {
				walk(c.Body)
			}
		}
	}
	walk(ss)
}

func isRead(v ir.Value, ss []ir.Stmt) bool {
	for _, s := range ss {
		inArgs := func(ins ir.Instr) bool {
			for _, a := range ins.Args {
				if a == v {
					return true
				}
			}
			return false
		}
		for _, ins := range s.ForInit {
			if inArgs(ins) {
				return true
			}
		}
		for _, ins := range s.ForCondPrep {
			if inArgs(ins) {
				return true
			}
		}
		for _, ins := range s.ForPost {
			if inArgs(ins) {
				return true
			}
		}
		for _, ins := range s.SwitchPrep {
			if inArgs(ins) {
				return true
			}
		}
		// CondRight zero-value is 0 (valid vreg) when unused — only on CF stmts
		if s.Kind == ir.SKFor || s.Kind == ir.SKIf || s.Kind == ir.SKDoWhile {
			if s.CondOp == "" || s.CondOp == "truthy" {
				if s.CondLeft == v {
					return true
				}
			} else if s.CondLeft == v || s.CondRight == v {
				return true
			}
		}
		if s.Kind == ir.SKInstr {
			if inArgs(s.Ins) {
				return true
			}
		} else if s.Kind == ir.SKFor {
			if isRead(v, s.ForBody) {
				return true
			}
		} else if s.Kind == ir.SKIf {
			if isRead(v, s.ThenBody) || isRead(v, s.ElseBody) {
				return true
			}
		} else if s.Kind == ir.SKSwitch {
			if s.SwitchOn == v {
				return true
			}
			for _, sc := range s.SwitchCases {
				if isRead(v, sc.Body) {
					return true
				}
			}
		} else if s.Kind == ir.SKDoWhile {
			if isRead(v, s.DoBody) {
				return true
			}
		}
	}
	return false
}

