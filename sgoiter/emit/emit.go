func sanitizeIdent(s string) string {
	if s == "" {
		return "x"
	}
	var b strings.Builder
	for i, r := range s {
		ok := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r == '_' || (i > 0 && r >= '0' && r <= '9')
		if ok {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" || (out[0] >= '0' && out[0] <= '9') {
		return "x" + out
	}
	if goKeywords[out] {
		return out + "_"
	}
	return out
}

func exportName(s string) string {
	s = sanitizeIdent(s)
	if s == "" {
		return s
	}
	if s[0] >= 'a' && s[0] <= 'z' {
		return strings.ToUpper(s[:1]) + s[1:]
	}
	return s
}

// uniqueExportName disambiguates Sigma0 vs sigma0 → Sigma0 / Sigma0_l
func uniqueExportName(cName string, taken map[string]bool) string {
	base := exportName(cName)
	if !taken[base] {
		taken[base] = true
		return base
	}
	alt := base
	if cName != "" && cName[0] >= 'a' && cName[0] <= 'z' {
		alt = base + "_l"
	} else {
		alt = base + "_u"
	}
	if !taken[alt] {
		taken[alt] = true
		return alt
	}
	for i := 2; ; i++ {
		n := fmt.Sprintf("%s_%d", base, i)
		if !taken[n] {
			taken[n] = true
			return n
		}
	}
}

// baseCallSym strips rules markConstCallArgs suffix "#cN".
func baseCallSym(sym string) string {
	if i := strings.Index(sym, "#c"); i >= 0 {
		return sym[:i]
	}
	return sym
}

func resolveGoName(e *env, sym string) string {
	sym = baseCallSym(sym)
	if strings.Contains(sym, "->") || strings.Contains(sym, ".") {
		clean := strings.ReplaceAll(sym, "->", ".")
		parts := strings.Split(clean, ".")
		res := sanitizeIdent(parts[0])
		for _, p := range parts[1:] {
			res += "." + exportName(p)
		}
		return res
	}
	if e != nil && e.goName != nil {
		if n, ok := e.goName[sym]; ok {
			return n
		}
		// case-insensitive fallback only if unique match
		low := strings.ToLower(sym)
		var hit string
		nHit := 0
		for c, g := range e.goName {
			if strings.ToLower(c) == low {
				hit = g
				nHit++
			}
		}
		if nHit == 1 {
			return hit
		}
	}
	return exportName(sym)
}

// emitBuiltinCall maps common C string/mem helpers to Go expressions.
// args are already rendered Go expressions.
func emitBuiltinCall(e *env, ins ir.Instr, sym string, args []string) string {
	low := strings.ToLower(sym)
	switch low {
	case "strchr":
		// C strchr: pointer to first c in s, else NULL. Go: s[i:] or nil.
		// Stops at embedded NUL (C string end) when present in the slice.
		if len(args) >= 2 {
			return fmt.Sprintf(`func() []byte { s := []byte(%s); c := byte(%s); for i := 0; i < len(s); i++ { if s[i] == c { return s[i:] }; if s[i] == 0 { break } }; return nil }()`, args[0], args[1])
		}
	case "memchr":
		if len(args) >= 3 {
			return fmt.Sprintf(`func() []byte { s := []byte(%s); c := byte(%s); n := int(%s); for i := 0; i < n && i < len(s); i++ { if s[i] == c { return s[i:] } }; return nil }()`, args[0], args[1], args[2])
		}
	case "strlen":
		if len(args) >= 1 {
			return fmt.Sprintf("uint64(len(%s))", args[0])
		}
	case "memcmp":
		if len(args) >= 3 {
			return fmt.Sprintf("func() int { a,b:=%s,%s; n:=int(%s); for i:=0;i<n&&i<len(a)&&i<len(b);i++ { if a[i]!=b[i] { if a[i]<b[i] { return -1 }; return 1 } }; return 0 }()", args[0], args[1], args[2])
		}
	case "memset":
		// memset(p, v, n)
		if len(args) >= 3 {
			if e != nil && len(ins.Args) > 0 {
				v0 := ins.Args[0]
				t0 := e.regType[v0]
				sname := string(t0)
				if e.isStructTypeName(sname) || e.findStruct(sname) != nil {
					st := e.findStruct(sname)
					targetName := strings.TrimPrefix(strings.TrimPrefix(sname, "*"), "[]")
					if st != nil {
						targetName = st.Name
					}
					arg0 := strings.TrimSuffix(strings.TrimPrefix(args[0], "&"), "[:]")
					if isZeroLit(args[1]) {
						if strings.HasPrefix(args[0], "&") || (!strings.HasPrefix(string(t0), "*") && !e.scalarPtr[v0]) {
							return fmt.Sprintf("%s = %s{}", arg0, exportName(targetName))
						}
						return fmt.Sprintf("*%s = %s{}", arg0, exportName(targetName))
					}
				}
				if strings.HasPrefix(args[0], "&") {
					base := strings.TrimPrefix(args[0], "&")
					if isZeroLit(args[1]) {
						if e.isStructTypeName(sname) {
							return fmt.Sprintf("%s = %s{}", base, exportName(sname))
						}
					}
				}
			}
			if isZeroLit(args[1]) {
				return fmt.Sprintf("clear(%s[:%s])", args[0], args[2])
			}
			return fmt.Sprintf("func() { p := %s; v := byte(%s); n := int(%s); for i := 0; i < n && i < len(p); i++ { p[i] = v } }()", args[0], args[1], args[2])
		}
	case "memcpy", "memmove":
		// element-wise copy
		if len(args) >= 3 {
			if e != nil && len(ins.Args) >= 2 {
				v0 := ins.Args[0]
				t0 := e.regType[v0]
				sname := string(t0)
				if e.isStructTypeName(sname) || e.findStruct(sname) != nil {
					lhs := "*" + args[0]
					rhs := "*" + args[1]
					if strings.HasPrefix(args[0], "&") {
						lhs = strings.TrimPrefix(args[0], "&")
					}
					if strings.HasPrefix(args[1], "&") {
						rhs = strings.TrimPrefix(args[1], "&")
					}
					return fmt.Sprintf("%s = %s", lhs, rhs)
				}
			}
			return fmt.Sprintf("copy(%s[:%s], %s[:%s])", args[0], args[2], args[1], args[2])
		}
	case "strcmp":
		if len(args) >= 2 {
			return fmt.Sprintf("func() int { a,b:=%s,%s; for i:=0; i<len(a) && i<len(b); i++ { if a[i]!=b[i] { if a[i]<b[i] { return -1 }; return 1 }; if a[i]==0 { return 0 } }; if len(a)<len(b) && (len(a)==0 || a[len(a)-1]!=0) { return -1 }; if len(a)>len(b) && (len(b)==0 || b[len(b)-1]!=0) { return 1 }; return 0 }()", args[0], args[1])
		}
	case "fabs":
		if len(args) >= 1 {
			return fmt.Sprintf("func() float64 { x := float64(%s); if x < 0 { return -x }; return x }()", args[0])
		}
	case "tolower":
		if len(args) >= 1 {
			return fmt.Sprintf("func() int { c := byte(%s); if c >= 'A' && c <= 'Z' { return int(c + 32) }; return int(c) }()", args[0])
		}
	}
	return ""
}

func isZeroLit(s string) bool {
	s = strings.TrimSpace(s)
	if s == "0" || s == "0x0" || s == "0x00" || s == "'\\x00'" || s == "'\\0'" || s == `"\x00"` {
		return true
	}
	if strings.HasSuffix(s, "(0)") || strings.HasSuffix(s, "(0x0)") {
		return true
	}
	return false
}

func isBoolExpr(s string) bool {
	s = strings.TrimSpace(s)
	// peel outer parens so "(((s == nil)))" still counts as bool
	for {
		if len(s) < 2 || s[0] != '(' || s[len(s)-1] != ')' {
			break
		}
		if !balancedParens(s[1 : len(s)-1]) {
			break
		}
		s = strings.TrimSpace(s[1 : len(s)-1])
	}
	if s == "true" || s == "false" {
		return true
	}
	// never treat IIFE / calls as bare bool for !=0 stripping
	if strings.Contains(s, "func(") {
		return false
	}
	// bare "!" not enough; need relational/logical (NOT << >>)
	if strings.Contains(s, "&&") || strings.Contains(s, "||") {
		return true
	}
	if strings.Contains(s, "==") || strings.Contains(s, "!=") {
		return true
	}
	if strings.Contains(s, "<=") || strings.Contains(s, ">=") {
		return true
	}
	// lone < or > but not part of << >>
	if hasCmpLTGT(s) {
		return true
	}
	if strings.Contains(s, "nil") {
		return true
	}
	if strings.HasPrefix(s, "!") && !strings.HasPrefix(s, "!=") {
		return true
	}
	return false
}

func hasCmpLTGT(s string) bool {
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c != '<' && c != '>' {
			continue
		}
		// skip << >>
		if i+1 < len(s) && s[i+1] == c {
			i++
			continue
		}
		// skip <= >=
		if i+1 < len(s) && s[i+1] == '=' {
			return true
		}
		return true
	}
	return false
}

func balancedParens(s string) bool {
	d := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			d++
		case ')':
			d--
			if d < 0 {
				return false
			}
		}
	}
	return d == 0
}

// foldRedundantBoolNe0 rewrites "(boolExpr) != 0" → "boolExpr" (nested parens OK).
func foldRedundantBoolNe0(block string) string {
	const suf = ") != 0"
	for round := 0; round < 64; round++ {
		i := strings.Index(block, suf)
		if i < 0 {
			break
		}
		// walk back to matching '('
		depth := 1
		j := i - 1
		for j >= 0 && depth > 0 {
			switch block[j] {
			case ')':
				depth++
			case '(':
				depth--
			}
			j--
		}
		if depth != 0 {
			// skip this occurrence
			block = block[:i] + ")" + " !=0" + block[i+len(suf):] // break loop progress? better skip
			// mark skip by temporary
			block = block[:i] + ")\x00!= 0" + block[i+len(suf):]
			continue
		}
		open := j + 1
		inner := block[open+1 : i]
		if isBoolExpr(inner) {
			block = block[:open] + "(" + strings.TrimSpace(inner) + ")" + block[i+len(suf):]
			continue
		}
		block = block[:i] + ")\x00!= 0" + block[i+len(suf):]
	}
	return strings.ReplaceAll(block, "\x00!= 0", " != 0")
}

// stripBoolNe0 removes redundant "(boolExpr) != 0" / "boolExpr != 0".
func stripBoolNe0(s string) string {
	s = strings.TrimSpace(s)
	for {
		if strings.HasSuffix(s, " != 0") {
			inner := strings.TrimSpace(s[:len(s)-len(" != 0")])
			if isBoolExpr(inner) {
				s = inner
				continue
			}
		}
		// (expr) != 0
		if strings.HasSuffix(s, ") != 0") {
			// find matching open
			core := strings.TrimSpace(s[:len(s)-len(" != 0")])
			if len(core) >= 2 && core[0] == '(' && core[len(core)-1] == ')' && balancedParens(core[1:len(core)-1]) {
				inner := strings.TrimSpace(core[1 : len(core)-1])
				if isBoolExpr(inner) {
					s = inner
					continue
				}
			}
		}
		break
	}
	return s
}

func (e *env) toBoolStr(v ir.Value, s string) string {
	s = strings.TrimSpace(s)
	if e.regType[v] == ir.TypBool || isBoolExpr(s) {
		return s
	}
	return fmt.Sprintf("(%s) != 0", s)
}

var iiifeBoolPat1 = regexp.MustCompile(`func\(\) int \{ if (.+?) \{ return 1 \}; return 0 \}\(\) != 0`)
var iiifeBoolPat2 = regexp.MustCompile(`func\(\) int \{ if (.+?) \{ return 1 \}; return 0 \}\(\) == 1`)

func isUsedAsCond(f *ir.Func, reg ir.Value) bool {
	if reg == 0 || f == nil {
		return false
	}
	condRegs := map[ir.Value]bool{}
	var markCond func(ss []ir.Stmt)
	markCond = func(ss []ir.Stmt) {
		for _, s := range ss {
			if s.Kind == ir.SKInstr && s.Ins.Sym == "__select" && len(s.Ins.Args) >= 1 {
				condRegs[s.Ins.Args[0]] = true
			}
			if s.Kind == ir.SKIf || s.Kind == ir.SKFor || s.Kind == ir.SKDoWhile {
				if s.CondOp == "" && s.CondLeft != 0 {
					condRegs[s.CondLeft] = true
				} else if s.CondOp == "!=" && s.CondRight == 0 && s.CondLeft != 0 {
					condRegs[s.CondLeft] = true
				}
			}
			markCond(s.ForBody)
			markCond(s.ThenBody)
			markCond(s.ElseBody)
			markCond(s.DoBody)
			for _, c := range s.SwitchCases {
				markCond(c.Body)
			}
		}
	}
	markCond(f.Stmts)

	var instrs []ir.Instr
	var collectInstrs func(ss []ir.Stmt)
	collectInstrs = func(ss []ir.Stmt) {
		for _, s := range ss {
			if s.Kind == ir.SKInstr {
				instrs = append(instrs, s.Ins)
			}
			instrs = append(instrs, s.ForInit...)
			instrs = append(instrs, s.ForPost...)
			instrs = append(instrs, s.SwitchPrep...)
			collectInstrs(s.ForBody)
			collectInstrs(s.ThenBody)
			collectInstrs(s.ElseBody)
			collectInstrs(s.DoBody)
			for _, c := range s.SwitchCases {
				collectInstrs(c.Body)
			}
		}
	}
	collectInstrs(f.Stmts)
	instrs = append(instrs, f.Body...)

	if f.Result == ir.TypBool {
		for _, ins := range instrs {
			if ins.Op == ir.OpReturn && len(ins.Args) > 0 {
				condRegs[ins.Args[0]] = true
			}
		}
	}

	// Propagate backwards through comparison instructions
	changed := true
	for changed {
		changed = false
		for _, ins := range instrs {
			if condRegs[ins.Dst] {
				if ins.Sym == "__cmp_&&" || ins.Sym == "__cmp_||" {
					for _, arg := range ins.Args {
						if arg != 0 && !condRegs[arg] {
							condRegs[arg] = true
							changed = true
						}
					}
				} else if (ins.Sym == "__cmp_==" || ins.Sym == "__cmp_!=") && len(ins.Args) == 2 {
					if arg0 := ins.Args[0]; arg0 != 0 && !condRegs[arg0] {
						for _, prev := range instrs {
							if prev.Dst == arg0 && strings.HasPrefix(prev.Sym, "__cmp_") {
								condRegs[arg0] = true
								changed = true
								break
							}
						}
					}
				}
			}
		}
	}
	return condRegs[reg]
}
