type Profile string

const ProfileGo127 Profile = "go127"

// Mode selects memory lowering for byte buffers.
type Mode string

const (
	ModeSafe   Mode = "safe"   // encoding/binary, bounds-friendly (default)
	ModeKernel Mode = "kernel" // LE host: unsafe word loads on aligned paths (xor…)
)

// Options for Emit.
type Options struct {
	Profile        Profile
	Mode           Mode
	PreferIR       bool     // skip kernel body overrides (absorb path)
	ExcludeSymbols []string // symboles exclus de l'émission (surpassés par hand_*.go)
}

// Emit is EmitOpts with safe mode (compat).
func Emit(m *ir.Module, profile Profile) (string, error) {
	return EmitOpts(m, Options{Profile: profile, Mode: ModeSafe})
}

func EmitOpts(m *ir.Module, opt Options) (string, error) {
	if m == nil {
		return "", fmt.Errorf("emit: nil module")
	}
	if opt.Profile == "" {
		opt.Profile = ProfileGo127
	}
	if opt.Profile != ProfileGo127 {
		return "", fmt.Errorf("emit: unsupported profile %q", opt.Profile)
	}
	if opt.Mode == "" {
		opt.Mode = ModeSafe
	}
	if opt.Mode != ModeSafe && opt.Mode != ModeKernel {
		return "", fmt.Errorf("emit: unsupported mode %q (safe|kernel)", opt.Mode)
	}
	pkg := sanitizeIdent(m.Name)
	if pkg == "" {
		pkg = "generated"
	}

	// callee signatures for arg casting + unique Go names (Sigma0 vs sigma0)
	callees := map[string]*ir.Func{}
	goName := map[string]string{} // exact C name → unique Go ident only
	taken := map[string]bool{}
	for i := range m.Funcs {
		callees[m.Funcs[i].Name] = &m.Funcs[i]
		callees[strings.ToLower(m.Funcs[i].Name)] = &m.Funcs[i]
		n := uniqueExportName(m.Funcs[i].Name, taken)
		goName[m.Funcs[i].Name] = n
	}

	var body strings.Builder
	needBin := false
	needBits := false
	needUnsafe := false
	gtypes := map[string]ir.TypeName{}
	glens := map[string]int64{}
	for _, g := range m.Globals {
		et := g.Type
		if et == "" {
			et = ir.TypUint8
		}
		nm := sanitizeIdent(g.Name)
		gtypes[nm] = et
		switch {
		case g.ZeroLen > 0:
			glens[nm] = int64(g.ZeroLen)
		case g.InitCSV != "":
			n := 0
			for _, p := range strings.Split(g.InitCSV, ",") {
				if strings.TrimSpace(p) != "" {
					n++
				}
			}
			glens[nm] = int64(n)
		case g.Rows > 0 && g.Cols > 0:
			glens[nm] = int64(g.Rows * g.Cols)
		case len(g.Data) > 0:
			glens[nm] = int64(len(g.Data))
		}
	}
	excludeMap := make(map[string]bool, len(opt.ExcludeSymbols)*2)
	for _, s := range opt.ExcludeSymbols {
		s = strings.TrimSpace(s)
		if s != "" {
			excludeMap[s] = true
			excludeMap[exportName(s)] = true
		}
	}

	for i := range m.Funcs {
		if excludeMap[m.Funcs[i].Name] || excludeMap[exportName(m.Funcs[i].Name)] {
			continue
		}
		e := newEnv(&m.Funcs[i])
		e.callees = callees
		e.goName = goName
		e.mode = opt.Mode
		e.preferIR = opt.PreferIR
		e.globalType = gtypes
		e.globalLen = glens
		var fb strings.Builder
		if err := emitFunc(&fb, &m.Funcs[i], e); err != nil {
			return "", err
		}
		if e.needBinary {
			needBin = true
		}
		if e.needBits {
			needBits = true
		}
		if e.needUnsafe {
			needUnsafe = true
		}
		body.WriteString(fb.String())
		body.WriteByte('\n')
	}

	var b strings.Builder
	b.WriteString("// Code generated by sgoiter emit go1.26; DO NOT EDIT.\n")
	if opt.Mode == ModeKernel {
		b.WriteString("// emit mode=kernel (unsafe LE word paths where documented)\n")
	}
	b.WriteString("package ")
	b.WriteString(pkg)
	b.WriteString("\n\n")
	// imports
	var imps []string
	if needBin {
		imps = append(imps, `"encoding/binary"`)
	}
	if needBits {
		imps = append(imps, `"math/bits"`)
	}
	if needUnsafe {
		imps = append(imps, `"unsafe"`)
	}
	switch len(imps) {
	case 0:
	case 1:
		b.WriteString("import " + imps[0] + "\n\n")
	default:
		b.WriteString("import (\n")
		for _, im := range imps {
			b.WriteString("\t" + im + "\n")
		}
		b.WriteString(")\n\n")
	}
	// struct types
	for _, st := range m.Structs {
		if excludeMap[st.Name] || excludeMap[exportName(st.Name)] {
			continue
		}
		fmt.Fprintf(&b, "type %s struct {\n", exportName(st.Name))
		for _, f := range st.Fields {
			fn := sanitizeIdent(f.Name)
			if f.ArrayLen > 0 {
				fmt.Fprintf(&b, "\t%s [%d]%s\n", exportName(fn), f.ArrayLen, goType(f.Type))
			} else if f.ArrayLen < 0 {
				// C pointer field → Go slice (argon2 inputs.pass, etc.)
				fmt.Fprintf(&b, "\t%s []%s\n", exportName(fn), goType(f.Type))
			} else {
				fmt.Fprintf(&b, "\t%s %s\n", exportName(fn), goType(f.Type))
			}
		}
		b.WriteString("}\n\n")
	}
	passedToCall := globalsPassedToCalls(m)
	for _, g := range m.Globals {
		nm := sanitizeIdent(g.Name)
		switch {
		case g.Data != "":
			// A printable C string table stays a constant: indexing a string
			// yields a byte just the same, with no slice header and nothing
			// mutable at package scope. Unless it is handed to a function, which
			// wants a []byte — monocypher passes its chacha20 constant along.
			if passedToCall[nm] {
				fmt.Fprintf(&b, "var %s = []byte(%q)\n", nm, g.Data)
			} else {
				fmt.Fprintf(&b, "const %s = %q\n", nm, g.Data)
			}
		case g.ZeroLen > 0:
			if passedToCall[nm] {
				fmt.Fprintf(&b, "var %s_arr [%d]byte\nvar %s = %s_arr[:]\n", nm, g.ZeroLen, nm, nm)
			} else {
				fmt.Fprintf(&b, "var %s = [%d]byte{}\n", nm, g.ZeroLen)
			}
		case g.InitCSV != "":
			if nm == "crypto_x25519_public_key_base_point" {
				fmt.Fprintf(&b, "var %s_arr = [32]byte{9}\nvar %s = %s_arr[:]\n", nm, nm, nm)
				continue
			}
			// parse hex/int list into Go composite
			gt := "uint64"
			switch g.Type {
			case ir.TypUint8:
				gt = "byte"
			case ir.TypUint32:
				gt = "uint32"
			case ir.TypInt, ir.TypInt64:
				gt = "int"
			}
			parts := strings.Split(g.InitCSV, ",")
			var vals []string
			for _, p := range parts {
				p = strings.TrimSpace(p)
				if p == "" {
					continue
				}
				p = strings.TrimRight(p, "uUlL")
				vals = append(vals, p)
			}
			// Fixed-size array, not a slice: the C table has a known extent.
			// A table handed to a function keeps its slice type.
			if passedToCall[nm] {
				fmt.Fprintf(&b, "var %s = []%s{%s}\n", nm, gt, strings.Join(vals, ", "))
			} else {
				fmt.Fprintf(&b, "var %s = [%d]%s{%s}\n", nm, len(vals), gt, strings.Join(vals, ", "))
			}
		default:
			fmt.Fprintf(&b, "var %s []byte\n", nm)
		}
	}
	if len(m.Globals) > 0 {
		b.WriteByte('\n')
	}
	b.WriteString(body.String())
	out := b.String()
	// Module-level: L32/R/Rotl32/Rotr64 helpers live outside any one emitFunc body.
	out = foldManualRotHelpers(out)
	out = archInlineRotlWrappers(out)
	out = archInlineRotrWrappers(out)
	out = archDeduplicateStores(out)
	out = archWipeToClear(out)
	out = archOptimizeBlockCopies(out)
	out = archOptimizeEndianHelpers(out)
	if strings.Contains(out, "bits.RotateLeft") && !strings.Contains(out, `"math/bits"`) {
		// inject bits import if helpers folded in RotateLeft without prior needBits
		out = strings.Replace(out, "package "+pkg+"\n\n", "package "+pkg+"\n\nimport \"math/bits\"\n\n", 1)
		if !strings.Contains(out, "import \"math/bits\"") && strings.Contains(out, "import (") {
			out = strings.Replace(out, "import (\n", "import (\n\t\"math/bits\"\n", 1)
		}
	}
	if strings.Contains(out, "binary.LittleEndian") && !strings.Contains(out, `"encoding/binary"`) {
		// inject binary import if helpers folded in binary.LittleEndian without prior needBin
		if strings.Contains(out, "import (") {
			out = strings.Replace(out, "import (\n", "import (\n\t\"encoding/binary\"\n", 1)
		} else if strings.Contains(out, "import \"math/bits\"") {
			out = strings.Replace(out, "import \"math/bits\"\n\n", "import (\n\t\"encoding/binary\"\n\t\"math/bits\"\n)\n\n", 1)
		} else {
			out = strings.Replace(out, "package "+pkg+"\n\n", "package "+pkg+"\n\nimport \"encoding/binary\"\n\n", 1)
		}
	}
	return out, nil
}

type divRec struct {
	src ir.Value
	k   int64
}

// shiftRec records a const-amount shift for ROT peephole.
type shiftRec struct {
	op  ir.Op
	src ir.Value
	amt int64
	typ ir.TypeName
	// amtReg holds the shift count when it is a register rather than a literal
	// — murmur3's rotl32(x, r) rotates by a parameter.
	amtReg ir.Value
	amtVar bool
}

// subConstRec is `constant - register`, the shape a rotation's complementary
// shift count takes: 32 - r.
type subConstRec struct {
	c int64
	v ir.Value
}

type env struct {
	f          *ir.Func
	globalType map[string]ir.TypeName // package-level table element types
	regName    map[ir.Value]string
	regType    map[ir.Value]ir.TypeName
	regPtr     map[ir.Value]bool
	elemIdx    map[ir.Value]bool
	stackArr   map[ir.Value]bool // local [N]T (not slice header)
	scalarPtr  map[ir.Value]bool // *T param (not []T)
	constImm   map[ir.Value]int64
	declared   map[ir.Value]bool
	dom        ir.TypeName
	needBinary bool
	needBits   bool
	needUnsafe bool
	mode       Mode
	preferIR   bool // disable body overrides (fnv/blake absorb tests)
	isAddrOf   map[ir.Value]bool
	isParam    map[ir.Value]bool
	callees    map[string]*ir.Func
	goName     map[string]string
	hoist      bool
	hoistTypes map[ir.Value]ir.TypeName
	// divInfo: dst of (x/k) → {x,k} for (x/k)*k fold
	divInfo map[ir.Value]divRec
	// foldImm: const values known before emit (for effective-read)
	foldImm map[ir.Value]int64
	// suppress: skip emit of pure assign (dead after fold / unread)
	suppress map[ir.Value]bool
	useCount map[ir.Value]int
	// noConstArg: loop-carried / offSlot — never substitute imm in e.arg (for conds)
	noConstArg map[ir.Value]bool
	// ind: indent depth (1 = function body)
	ind int
	// cseExpr: identical pure rhs → reuse vreg (e.g. i&^7 ×3)
	cseExpr map[string]string // rhs → name holding it
	// writeCount: static write sites per vreg (copy-prop safety)
	writeCount map[ir.Value]int
	// emitted: vregs that were physically emitted in Pass 2
	emitted map[ir.Value]bool
	// shiftDef: dst of shl/shr with const amount (ROT detection)
	shiftDef map[ir.Value]shiftRec
	// valRoot: copy-chain root (Mov) for rotate src equality
	valRoot map[ir.Value]ir.Value
	// xorPair: dst of a^b → sorted (root(a),root(b)) — equal pairs ⇒ same src for ROTR
	xorPair map[ir.Value][2]ir.Value
	// loadKey: dst of load(base,idx) with const idx → (base,idx) for alias eq
	loadKey map[ir.Value][2]ir.Value
	// subConst: dst of `const - reg`, needed to recognise a variable rotation
	subConst map[ir.Value]subConstRec
	// forceCondBool: emit __cmp_* as Go bool (short-circuit for leaves)
	forceCondBool bool
	// declType: the C declaration's type for a local. It outranks whatever a
	// later assignment would infer — `u32 u` stays 32 bits for its whole life,
	// which is what makes `u = (u<<8)|x[i]` accumulate instead of truncate.
	declType map[ir.Value]ir.TypeName
	// Front may hoist static const to package global then still emit a shadowing
	// Alloca; only alias when Imm matches that global's element count.
	lastGlobalName string
	lastGlobalLen  int64
	globalLen      map[string]int64
}

func newEnv(fn *ir.Func) *env {
	dom := fn.Result
	if dom == "" || dom == ir.TypVoid {
		// void/empty: prefer integer width from non-pointer params, else int
		dom = ir.TypInt
		for _, p := range fn.Params {
			if p.Ptr || p.ArrayLen > 0 {
				continue
			}
			if p.Type == ir.TypUint64 || p.Type == ir.TypUint32 || p.Type == ir.TypInt {
				dom = p.Type
				break
			}
		}
	}
	return &env{
		f:          fn,
		regName:    map[ir.Value]string{},
		regType:    map[ir.Value]ir.TypeName{},
		regPtr:     map[ir.Value]bool{},
		elemIdx:    map[ir.Value]bool{},
		stackArr:   map[ir.Value]bool{},
		scalarPtr:  map[ir.Value]bool{},
		constImm:   map[ir.Value]int64{},
		declared:   map[ir.Value]bool{},
		isAddrOf:   map[ir.Value]bool{},
		dom:        dom,
		callees:    map[string]*ir.Func{},
		divInfo:    map[ir.Value]divRec{},
		foldImm:    map[ir.Value]int64{},
		suppress:   map[ir.Value]bool{},
		useCount:   map[ir.Value]int{},
		noConstArg: map[ir.Value]bool{},
		ind:        1,
		cseExpr:    map[string]string{},
		writeCount: map[ir.Value]int{},
		shiftDef:   map[ir.Value]shiftRec{},
		valRoot:    map[ir.Value]ir.Value{},
		xorPair:    map[ir.Value][2]ir.Value{},
		loadKey:    map[ir.Value][2]ir.Value{},
		subConst:   map[ir.Value]subConstRec{},
		declType:   map[ir.Value]ir.TypeName{},
	}
}

func (e *env) rootOf(v ir.Value) ir.Value {
	seen := 0
	for {
		r, ok := e.valRoot[v]
		if !ok || r == v || seen > 8 {
			return v
		}
		v = r
		seen++
	}
}

func (e *env) eqVal(a, b ir.Value) bool {
	ra, rb := e.rootOf(a), e.rootOf(b)
	if ra == rb {
		return true
	}
	la, oka := e.loadKey[ra]
	lb, okb := e.loadKey[rb]
	return oka && okb && la == lb
}

func (e *env) sameRotSrc(a, b ir.Value) bool {
	if e.eqVal(a, b) {
		return true
	}
	pa, oka := e.xorPair[e.rootOf(a)]
	pb, okb := e.xorPair[e.rootOf(b)]
	if !oka || !okb {
		return false
	}
	// pairs equal under load-alias (order-independent)
	return (e.eqVal(pa[0], pb[0]) && e.eqVal(pa[1], pb[1])) ||
		(e.eqVal(pa[0], pb[1]) && e.eqVal(pa[1], pb[0]))
}

func (e *env) pad() string {
	if e.ind < 1 {
		return "\t"
	}
	return strings.Repeat("\t", e.ind)
}

func (e *env) clearCSE() {
	e.cseExpr = map[string]string{}
}

// killCSEBase drops CSE entries whose rhs mentions a memory base (after store).
func killCSEBase(e *env, base string) {
	if base == "" {
		return
	}
	for k := range e.cseExpr {
		if strings.Contains(k, base) {
			delete(e.cseExpr, k)
		}
	}
}

func (e *env) line(b *strings.Builder, format string, args ...any) {
	b.WriteString(e.pad())
	fmt.Fprintf(b, format, args...)
}

func (e *env) lines(b *strings.Builder, s string) {
	b.WriteString(e.pad())
	b.WriteString(s)
}

func wrapInt(s string) string {
	if strings.HasPrefix(s, "int(") && strings.HasSuffix(s, ")") {
		return s
	}
	// bare decimal / hex literal — already an untyped int constant
	if isIntLit(s) {
		return s
	}
	return "int(" + s + ")"
}

func isIntLit(s string) bool {
	if s == "" {
		return false
	}
	i := 0
	if s[0] == '-' {
		if len(s) == 1 {
			return false
		}
		i = 1
	}
	if strings.HasPrefix(s[i:], "0x") || strings.HasPrefix(s[i:], "0X") {
		i += 2
		if i >= len(s) {
			return false
		}
		for ; i < len(s); i++ {
			c := s[i]
			if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F')) {
				return false
			}
		}
		return true
	}
	for ; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

func (e *env) nameOf(v ir.Value) string {
	if n, ok := e.regName[v]; ok {
		return n
	}
	return fmt.Sprintf("v%d", int(v))
}

func (e *env) arg(v ir.Value, ctx ir.TypeName) string {
	if imm, ok := e.constImm[v]; ok && !e.noConstArg[v] {
		return formatImm(imm, ctx)
	}
	n := e.nameOf(v)
	if e.isAddrOf[v] {
		n = "&" + n
	}
	if (e.stackArr[v] || ((e.elemIdx[v] || e.regPtr[v]) && strings.Contains(n, "."))) && !strings.HasSuffix(n, "[:]") && !strings.HasPrefix(n, "&") && !strings.HasPrefix(n, "func(") {
		return n + "[:]"
	}
	t := e.regType[v]
	if ctx != "" && t != "" && t != ctx && !e.regPtr[v] && t != ir.TypBool {
		return fmt.Sprintf("%s(%s)", goType(ctx), n)
	}
	return n
}

func emitFunc(b *strings.Builder, f *ir.Func, e *env) error {
	e.f = f
	e.regPtr = map[ir.Value]bool{}
	e.regType = map[ir.Value]ir.TypeName{}
	e.regName = map[ir.Value]string{}
	e.declared = map[ir.Value]bool{}
	e.emitted = map[ir.Value]bool{}
	e.constImm = map[ir.Value]int64{}
	e.elemIdx = map[ir.Value]bool{}
	e.stackArr = map[ir.Value]bool{}
	e.scalarPtr = map[ir.Value]bool{}
	e.isAddrOf = map[ir.Value]bool{}
	e.isParam = map[ir.Value]bool{}
	e.divInfo = map[ir.Value]divRec{}
	e.foldImm = map[ir.Value]int64{}
	e.suppress = map[ir.Value]bool{}
	e.useCount = map[ir.Value]int{}
	e.shiftDef = map[ir.Value]shiftRec{}
	e.valRoot = map[ir.Value]ir.Value{}
	e.xorPair = map[ir.Value][2]ir.Value{}
	e.loadKey = map[ir.Value][2]ir.Value{}
	e.noConstArg = map[ir.Value]bool{}
	e.ind = 1
	e.cseExpr = map[string]string{}
	e.writeCount = map[ir.Value]int{}
	for _, p := range f.Params {
		e.isParam[p.Reg] = true
	}
	f.EnsureStmts()
	countUses(f.Stmts, e.useCount)
	countWrites(f.Stmts, e.writeCount)
	markDivMulFolds(f.Stmts, e)
	// Counters that only ever walk an array are born int, which removes the
	// conversion at each index instead of wrapping every use.
	e.declType = map[ir.Value]ir.TypeName{}
	e.subConst = map[ir.Value]subConstRec{}
	for v := range indexOnlyRegs(f) {
		e.regType[v] = ir.TypInt
		e.declType[v] = ir.TypInt
	}
	b.WriteString("func ")
	fn := exportName(f.Name)
	if e.goName != nil {
		if n, ok := e.goName[f.Name]; ok {
			fn = n
		}
	}
	b.WriteString(fn)
	b.WriteByte('(')
	for i, p := range f.Params {
		if i > 0 {
			b.WriteString(", ")
		}
		// FillStubs marker: variadic any
		if p.Type == StubParamType {
			b.WriteString("args ...any")
			continue
		}
		nm := sanitizeIdent(p.Name)
		b.WriteString(nm)
		b.WriteByte(' ')
		if p.StructName != "" {
			// ge_precomp comb[8] → []Ge_precomp (not *Ge_precomp)
			if p.ArrayLen > 0 {
				b.WriteString("[]" + exportName(p.StructName))
				e.elemIdx[p.Reg] = true
			} else {
				b.WriteString("*" + exportName(p.StructName))
			}
			e.regName[p.Reg] = nm
			e.regPtr[p.Reg] = true
			e.regType[p.Reg] = p.Type
			e.declared[p.Reg] = true
			continue
		}
		if p.Ptr {
			// Bare T* only when never indexed in this fn (chacha *a); buffers stay []T.
			if p.ArrayLen == 0 && (p.Type == ir.TypUint32 || p.Type == ir.TypUint64 || p.Type == ir.TypInt32 || p.Type == ir.TypInt64 || p.Type == ir.TypFloat32 || p.Type == ir.TypFloat64) &&
				ptrUsedAsScalarOnly(f, p.Reg) {
				b.WriteString("*" + goType(p.Type))
				e.scalarPtr[p.Reg] = true
			} else {
				switch p.Type {
				case ir.TypUint8:
					b.WriteString("[]byte")
				case ir.TypUint32:
					b.WriteString("[]uint32")
				case ir.TypUint64:
					b.WriteString("[]uint64")
				case ir.TypInt32:
					b.WriteString("[]int32")
				case ir.TypInt64:
					b.WriteString("[]int64")
				case ir.TypFloat32:
					b.WriteString("[]float32")
				case ir.TypFloat64:
					b.WriteString("[]float64")
				default:
					if p.Type != "" && p.Type != ir.TypInt {
						b.WriteString("*" + exportName(string(p.Type)))
					} else {
						b.WriteString("[]" + goType(p.Type))
					}
				}
			}
		} else {
			b.WriteString(goType(p.Type))
		}
		e.regName[p.Reg] = nm
		e.regType[p.Reg] = p.Type
		e.regPtr[p.Reg] = p.Ptr || p.ArrayLen > 0
		if p.ArrayLen > 0 {
			e.elemIdx[p.Reg] = true
		} else if p.Ptr && p.Type != ir.TypUint8 && !e.scalarPtr[p.Reg] {
			e.elemIdx[p.Reg] = p.Type == ir.TypUint32 || p.Type == ir.TypUint64 || p.Type == ir.TypInt32 || p.Type == ir.TypInt64 || p.Type == ir.TypFloat32 || p.Type == ir.TypFloat64
		}
		e.declared[p.Reg] = true
	}
	b.WriteByte(')')
	if f.Result != ir.TypVoid && f.Result != "" {
		b.WriteByte(' ')
		b.WriteString(goType(f.Result))
	}
	b.WriteString(" {\n")
	// An unharvested symbol that the module actually calls must fail loudly.
	// Returning zero silently made Par25519 read a buffer Pack25519 never
	// filled, and the bench stayed green because nothing calls either one.
	if IsStub(f) {
		fmt.Fprintf(b, "\tpanic(\"sgoiter: %s was not harvested from the C source — this stub has no body\")\n}\n\n", f.Name)
		return nil
	}
	// Full kernel override: emit body only (no IR hoist locals — they clash with
	// override names like v0/v3 and leave dead var blocks).
	if ob, skip := tryKernelOverride(f, e); ob != "" && skip {
		stripped := ob
		if strings.Contains(stripped, "bits.RotateLeft") {
			e.needBits = true
		}
		if strings.Contains(stripped, "binary.") {
			e.needBinary = true
		}
		b.WriteString(stripped)
		b.WriteString("}\n")
		return nil
	}
	// two-pass: collect assignments then emit with function-scoped vars
	e.hoist = true
	e.hoistTypes = map[ir.Value]ir.TypeName{}
	var discard strings.Builder
	if err := emitStmts(&discard, e, f.Stmts); err != nil {
		return err
	}
	// hoist only multi-write temps; single-write uses := at first assign (I2)
	hoisted := map[ir.Value]bool{}
	// register order, not map order: the var block is emitted here and map
	// iteration is randomized, which made the emitted file vary run to run.
	hoistOrder := make([]ir.Value, 0, len(e.hoistTypes))
	for v := range e.hoistTypes {
		hoistOrder = append(hoistOrder, v)
	}
	sort.Slice(hoistOrder, func(i, j int) bool { return hoistOrder[i] < hoistOrder[j] })
	for _, v := range hoistOrder {
		if e.isParam[v] {
			continue
		}
		if n, ok := e.regName[v]; ok && n != fmt.Sprintf("v%d", int(v)) {
			continue // aliased to another register or expression
		}
		if e.suppress[v] || !isRead(v, f.Stmts) {
			continue // never read / folded away
		}
		if e.writeCount[v] <= 1 {
			continue // := at first write
		}
		t := e.regType[v]
		if t == "" {
			t = e.dom
		}
		gt := goType(t)
		if gt == "" {
			gt = "int"
		}
		if e.regPtr[v] {
			if e.scalarPtr[v] {
				gt = "*" + goType(t)
			} else if t == ir.TypUint8 || t == "" {
				gt = "[]byte"
			} else {
				gt = "[]" + goType(t)
			}
		}
		fmt.Fprintf(b, "%svar %s %s\n", e.pad(), e.nameOf(v), gt)
		hoisted[v] = true
	}
	e.hoist = false
	e.cseExpr = map[string]string{} // fresh CSE for real emit
	e.shiftDef = map[ir.Value]shiftRec{}
	e.valRoot = map[ir.Value]ir.Value{}
	e.xorPair = map[ir.Value][2]ir.Value{}
	e.loadKey = map[ir.Value][2]ir.Value{}
	e.constImm = map[ir.Value]int64{}
	e.noConstArg = map[ir.Value]bool{}
	// declared/regName rebuild: params + printed vars only (drop hoist pure-alias pollution)
	e.declared = map[ir.Value]bool{}
	e.regName = map[ir.Value]string{}
	for v, t := range e.hoistTypes {
		e.regType[v] = t
	}
	for _, p := range f.Params {
		nm := sanitizeIdent(p.Name)
		e.regName[p.Reg] = nm
		e.regType[p.Reg] = p.Type
		e.regPtr[p.Reg] = p.Ptr || p.ArrayLen > 0
		e.declared[p.Reg] = true
		if e.scalarPtr[p.Reg] {
			// keep
		} else if p.ArrayLen > 0 {
			e.elemIdx[p.Reg] = true
		} else if p.Ptr && p.Type != ir.TypUint8 {
			e.elemIdx[p.Reg] = p.Type == ir.TypUint32 || p.Type == ir.TypUint64
		}
	}
	for v := range hoisted {
		e.declared[v] = true
		e.regName[v] = e.nameOf(v)
	}
	var body strings.Builder
	fStmts := f.Stmts
	if ob, skip := tryKernelOverride(f, e); ob != "" {
		body.WriteString(ob)
		if skip {
			fStmts = nil
		}
	}
	if fStmts != nil {
		if err := emitStmts(&body, e, fStmts); err != nil {
			return err
		}
	}
	// b holds signature + "{\n" + vars; strip dead vars from vars+body
	pre := b.String()
	idx := strings.LastIndex(pre, "{\n")
	if idx < 0 {
		b.WriteString(body.String())
		b.WriteString("}\n")
		return nil
	}
	head := pre[:idx+2]
	varsAnd := pre[idx+2:]
	// Classic densify chain + L32/R → bits.Rotate* (Gemini rec 2).
	// foldLiveRangeCopies / foldCrcBitSteps stay unit-tested only — CRC/mono regressions.
	stripped := stripDeadVars(stripDeadAssigns(foldTempCopies(foldRotateExprs(foldSingleUseExprs(foldRotateExprs(foldSingleUseExprs(foldTempCopies(varsAnd + body.String()))))))))
	stripped = foldManualRotHelpers(stripped)
	stripped = foldIdentityCallCast(stripped)
	stripped = foldRedundantBoolNe0(stripped)
	stripped = dropRedundantParens(stripped)
	stripped = charLiteralsForBytes(stripped)
	stripped = dropDoubleCasts(stripped)
	stripped = foldNegatedMask(stripped)
	// shift counts first: the index narrowing below matches on `>> 18`, not on
	// the `>> uint8(18)` the emitter produces
	stripped = bareShiftCounts(stripped)
	stripped = dropIdentityCasts(stripped, goType(f.Result), paramTypes(f))
	stripped = foldPostIncStore(stripped)
	stripped = hoistLoopGuards(stripped)
	stripped = dropRedundantAlignMask(stripped)
	stripped = bceIndexLoops(stripped)
	// archArrayNotSlice is NOT applied globally: stack arrays are often passed as
	// []T to callees (monocypher). Overrides use [N]T explicitly where safe.
	stripped = archInlineRotlWrappers(stripped)
	stripped = archInlineRotrWrappers(stripped)
	stripped = archDeduplicateStores(stripped)
	stripped = archWipeToClear(stripped)
	stripped = archOptimizeBlockCopies(stripped)
	stripped = archNormalizeNegInduction(stripped)
	if e.mode == ModeKernel {
		stripped = rewriteKernelLELoads(stripped)
	}
	if strings.Contains(stripped, "bits.RotateLeft") {
		e.needBits = true
	}
	if strings.Contains(stripped, "unsafe.") {
		e.needUnsafe = true
	}
	if !strings.Contains(stripped, "binary.") {
		e.needBinary = false
	}
	// N7 absorb: FNV-style byte-hash unroll on IR body.
	stripped = maybePostUnrollHashes(stripped)
	// N5 absorb: murmur neg-count loop → forward.
	stripped = maybeRewriteMurmurLoop(stripped)
	// Drop dead Rotl32 wrapper if fully inlined.
	stripped = archInlineRotlWrappers(stripped)
	stripped = foldManualRotHelpers(stripped)
	// Passes d'idiomatisme et d'arbres de calcul Go (Phases 1, 2 & 3)
	stripped = archTransformCopyClearLoops(stripped)
	stripped = archCompoundAssigns(stripped)
	stripped = archStripIndexIntCasts(stripped)
	stripped = archFoldPingPongCasts(stripped)
	stripped = archStripRedundantLiteralCasts(stripped)
	stripped = archFoldRotateLeftConstants(stripped)
	stripped = archSimplifyDoubleNegations(stripped)
	stripped = archFoldGapLiteralConstants(stripped)
	stripped = archUnrollBlake2bSigma(stripped)
	stripped = archUnrollX25519InverseChain(stripped)
	stripped = archBuiltinMinMax(stripped)
	stripped = archBalanceAdditionTrees(stripped)
	stripped = archPowerOfTwoShifts(stripped)
	stripped = archCleanupWipeAveux(stripped)
	// Post-unroll and copy/clear loop transforms may leave dead idx locals.
	stripped = stripDeadVars(stripDeadAssigns(stripped))
	b.Reset()
	b.WriteString(head)
	b.WriteString(stripped)
	b.WriteString("}\n")
	return nil
}

func emitStmts(b *strings.Builder, e *env, ss []ir.Stmt) error {
	for i, s := range ss {
		if err := emitStmt(b, e, s, ss, i); err != nil {
			return err
		}
	}
	return nil
}

func emitStmt(b *strings.Builder, e *env, s ir.Stmt, ss []ir.Stmt, stmtIdx int) error {
	switch s.Kind {
	case ir.SKInstr:
		return emitIns(b, e, s.Ins, ss, stmtIdx)
	case ir.SKFor:
		e.clearCSE()
		for _, ins := range s.ForInit {
			if err := emitIns(b, e, ins, nil, 0); err != nil {
				return err
			}
		}
		if len(s.ForCondPrep) > 0 {
			// short-circuit && : emit conjuncts in order so loads after bounds checks
			if emitForShortCircuit(b, e, s) {
				return nil
			}
			e.lines(b, "for {\n")
			e.ind++
			e.clearCSE()
			for _, ins := range s.ForCondPrep {
				if err := emitIns(b, e, ins, nil, 0); err != nil {
					return err
				}
			}
			e.lines(b, "if !("+condStr(e, s)+") { break }\n")
			if err := emitStmts(b, e, s.ForBody); err != nil {
				return err
			}
			for _, ins := range s.ForPost {
				if err := emitIns(b, e, ins, nil, 0); err != nil {
					return err
				}
			}
			e.ind--
			e.lines(b, "}\n")
			e.clearCSE()
			return nil
		}
		e.lines(b, "for "+condStr(e, s)+" {\n")
		e.ind++
		e.clearCSE()
		if err := emitStmts(b, e, s.ForBody); err != nil {
			return err
		}
		for _, ins := range s.ForPost {
			if err := emitIns(b, e, ins, nil, 0); err != nil {
				return err
			}
		}
		e.ind--
		e.lines(b, "}\n")
		e.clearCSE()
		return nil
	case ir.SKSwitch:
		for _, ins := range s.SwitchPrep {
			if err := emitIns(b, e, ins, nil, 0); err != nil {
				return err
			}
		}
		e.lines(b, "switch "+e.arg(s.SwitchOn, e.dom)+" {\n")
		e.ind++
		for i, c := range s.SwitchCases {
			if len(c.Labels) == 0 {
				e.lines(b, "default:\n")
			} else {
				for _, lab := range c.Labels {
					e.line(b, "case %d:\n", lab)
				}
			}
			e.ind++
			e.clearCSE()
			if err := emitStmts(b, e, c.Body); err != nil {
				return err
			}
			e.ind--
			if i < len(s.SwitchCases)-1 {
				e.lines(b, "fallthrough\n")
			}
		}
		e.ind--
		e.lines(b, "}\n")
		e.clearCSE()
		return nil
	case ir.SKDoWhile:
		if doWhileOnce(e, s) {
			if err := emitStmts(b, e, s.DoBody); err != nil {
				return err
			}
			return nil
		}
		e.lines(b, "for {\n")
		e.ind++
		e.clearCSE()
		if err := emitStmts(b, e, s.DoBody); err != nil {
			return err
		}
		for _, ins := range s.ForInit {
			if err := emitIns(b, e, ins, nil, 0); err != nil {
				return err
			}
		}
		e.lines(b, "if !("+condStr(e, s)+") { break }\n")
		e.ind--
		e.lines(b, "}\n")
		e.clearCSE()
		return nil
	case ir.SKIf:
		for _, ins := range s.ForInit {
			if err := emitIns(b, e, ins, nil, 0); err != nil {
				return err
			}
		}
		cs := condStr(e, s)
		if s.CondNot {
			cs = "!(" + cs + ")"
		}
		e.lines(b, "if "+cs+" {\n")
		e.ind++
		e.clearCSE()
		if err := emitStmts(b, e, s.ThenBody); err != nil {
			return err
		}
		e.ind--
		if len(s.ElseBody) > 0 {
			e.lines(b, "} else {\n")
			e.ind++
			e.clearCSE()
			if err := emitStmts(b, e, s.ElseBody); err != nil {
				return err
			}
			e.ind--
		}
		e.lines(b, "}\n")
		// CSE from then/else must not leak (base64: v4+1 aliased to v63 only defined in then)
		e.clearCSE()
		return nil
	default:
		return fmt.Errorf("emit: stmt kind %v", s.Kind)
	}
}

// emitForShortCircuit emits for{ check1; check2; body } for &&-chains in ForCondPrep
// so loads on the right of && run only after left succeeds (C short-circuit).
func emitForShortCircuit(b *strings.Builder, e *env, s ir.Stmt) bool {
	if s.CondOp != "truthy" && s.CondOp != "" {
		return false
	}
	defs := map[ir.Value]ir.Instr{}
	for _, ins := range s.ForCondPrep {
		defs[ins.Dst] = ins
	}
	leaves := flattenLandLeaves(defs, s.CondLeft)
	if len(leaves) < 2 {
		return false
	}
	// only worth it if some leaf depends on a Load
	hasLoadDep := false
	for _, leaf := range leaves {
		if prepHasLoad(defs, leaf) {
			hasLoadDep = true
			break
		}
	}
	if !hasLoadDep {
		return false
	}
	e.lines(b, "for {\n")
	e.ind++
	e.clearCSE()
	emitted := map[ir.Value]bool{}
	for _, leaf := range leaves {
		if err := emitPrepDeps(b, e, leaf, defs, emitted); err != nil {
			// fall back: abort this path by panicking into normal? return false mid-write is bad
			// emitPrepDeps only fails on emitIns — rare; keep going
			_ = err
		}
		// leaf is a __cmp_* or value — emit as break check
		e.lines(b, "if !("+boolOfVreg(e, leaf)+") { break }\n")
	}
	if err := emitStmts(b, e, s.ForBody); err != nil {
		return true // already wrote for{ — must finish
	}
	for _, ins := range s.ForPost {
		_ = emitIns(b, e, ins, nil, 0)
	}
	e.ind--
	e.lines(b, "}\n")
	e.clearCSE()
	return true
}

func flattenLandLeaves(defs map[ir.Value]ir.Instr, v ir.Value) []ir.Value {
	ins, ok := defs[v]
	if !ok {
		return []ir.Value{v}
	}
	if strings.HasPrefix(ins.Sym, "__cmp_&&") && len(ins.Args) == 2 {
		left := flattenLandLeaves(defs, ins.Args[0])
		right := flattenLandLeaves(defs, ins.Args[1])
		return append(left, right...)
	}
	return []ir.Value{v}
}

func prepHasLoad(defs map[ir.Value]ir.Instr, v ir.Value) bool {
	seen := map[ir.Value]bool{}
	var walk func(ir.Value) bool
	walk = func(x ir.Value) bool {
		if seen[x] {
			return false
		}
		seen[x] = true
		ins, ok := defs[x]
		if !ok {
			return false
		}
		if ins.Op == ir.OpLoad {
			return true
		}
		for _, a := range ins.Args {
			if walk(a) {
				return true
			}
		}
		return false
	}
	return walk(v)
}

func emitPrepDeps(b *strings.Builder, e *env, v ir.Value, defs map[ir.Value]ir.Instr, emitted map[ir.Value]bool) error {
	if emitted[v] {
		return nil
	}
	ins, ok := defs[v]
	if !ok {
		return nil
	}
	for _, a := range ins.Args {
		if err := emitPrepDeps(b, e, a, defs, emitted); err != nil {
			return err
		}
	}
	// skip intermediate && nodes — only emit real ops
	if strings.HasPrefix(ins.Sym, "__cmp_&&") || strings.HasPrefix(ins.Sym, "__cmp_||") {
		emitted[v] = true
		return nil
	}
	emitted[v] = true
	// cmp leaves used as if !v must be Go bool
	if strings.HasPrefix(ins.Sym, "__cmp_") {
		e.forceCondBool = true
		err := emitIns(b, e, ins, nil, 0)
		e.forceCondBool = false
		return err
	}
	return emitIns(b, e, ins, nil, 0)
}

func boolOfVreg(e *env, v ir.Value) string {
	if e.regType[v] == ir.TypBool {
		return e.nameOf(v)
	}
	// comparison already emitted as bool assign
	n := e.nameOf(v)
	if isBoolExpr(n) {
		return n
	}
	// vreg holding 0/1 or bool
	if t := e.regType[v]; t == ir.TypBool {
		return n
	}
	return n // after isUsedAsCond emit, cmp results are bool
}

func condStr(e *env, s ir.Stmt) string {
	// pointer NULL checks
	if e.regPtr[s.CondLeft] && (s.CondOp == "!=" || s.CondOp == "==" || s.CondOp == "truthy" || s.CondOp == "") {
		if s.CondOp == "truthy" || s.CondOp == "" {
			return e.nameOf(s.CondLeft) + " != nil"
		}
		if imm, ok := e.constImm[s.CondRight]; ok && imm == 0 {
			if s.CondOp == "!=" {
				return e.nameOf(s.CondLeft) + " != nil"
			}
			return e.nameOf(s.CondLeft) + " == nil"
		}
	}
	ctx := e.regType[s.CondLeft]
	if ctx == "" {
		ctx = e.dom
	}
	if s.CondOp == "truthy" || s.CondOp == "" {
		arg := e.arg(s.CondLeft, ctx)
		if e.regType[s.CondLeft] == ir.TypBool || isBoolExpr(arg) {
			// strip accidental "(bool) != 0" if nested
			return stripBoolNe0(arg)
		}
		return arg + " != 0"
	}
	rctx := e.regType[s.CondRight]
	if rctx == "" {
		rctx = ctx
	}
	// unify comparison types (size_t i < len)
	if ctx != rctx {
		switch {
		case ctx == ir.TypUint64 || rctx == ir.TypUint64:
			ctx, rctx = ir.TypUint64, ir.TypUint64
		case ctx == ir.TypUint32 || rctx == ir.TypUint32:
			ctx, rctx = ir.TypUint32, ir.TypUint32
		default:
			ctx, rctx = ir.TypInt, ir.TypInt
		}
	}
	return fmt.Sprintf("%s %s %s", e.arg(s.CondLeft, ctx), s.CondOp, e.arg(s.CondRight, rctx))
}

func emitIns(b *strings.Builder, e *env, ins ir.Instr, ss []ir.Stmt, stmtIdx int) error {
	switch ins.Op {
	case ir.OpNop:
		return nil
	case ir.OpConst:
		e.constImm[ins.Dst] = ins.Imm
		if ins.Elem != "" {
			e.regType[ins.Dst] = ins.Elem
		}
		// leave regType unset so use-site picks context; Mov clears constImm if slot reused
		return nil
	case ir.OpMov:
		delete(e.constImm, ins.Dst)
		// C declaration with an initializer: the declared type wins over the
		// initializer's. `u32 u = x[3]` must hold 32 bits, not the byte's 8.
		if ins.Sym == "decl" && ins.Elem != "" {
			e.declType[ins.Dst] = ins.Elem
			e.regType[ins.Dst] = ins.Elem
			writeAssign(b, e, ins.Dst, e.arg(ins.Args[0], ins.Elem))
			e.regType[ins.Dst] = ins.Elem
			// constImm stays deleted: a declared local is assigned again inside
			// loops, and substituting its initial value there re-seeded the fnv
			// accumulator on every iteration.
			return nil
		}
		// offSlot cursor is always uint64 byte offset
		if ins.Sym == "offslot" || ins.Elem == ir.TypUint64 {
			ctx := ir.TypUint64
			if ins.Elem != "" {
				ctx = ins.Elem
			}
			e.regType[ins.Dst] = ctx
			e.noConstArg[ins.Dst] = true // loop-carried cursor
			writeAssign(b, e, ins.Dst, e.arg(ins.Args[0], ctx))
			e.regType[ins.Dst] = ctx
			// keep constImm for x+0 fold in same straight-line, but arg() won't inline it
			if imm, ok := e.constImm[ins.Args[0]]; ok {
				e.constImm[ins.Dst] = imm
			} else {
				delete(e.constImm, ins.Dst)
			}
			return nil
		}
		// global bind: v = globalName (module string table)
		if strings.HasPrefix(ins.Sym, "global:") {
			gname := sanitizeIdent(ins.Sym[len("global:"):])
			e.regPtr[ins.Dst] = true
			gt := ir.TypUint8
			if e.globalType != nil {
				if t, ok := e.globalType[gname]; ok && t != "" {
					gt = t
				}
			}
			e.regType[ins.Dst] = gt
			e.elemIdx[ins.Dst] = true
			writeAssign(b, e, ins.Dst, gname)
			e.lastGlobalName = gname
			if e.globalLen != nil {
				e.lastGlobalLen = e.globalLen[gname]
			} else {
				e.lastGlobalLen = 0
			}
			return nil
		}
		// explicit C cast
		if ins.Sym == "cast" && ins.Elem != "" {
			e.regType[ins.Dst] = ins.Elem
			writeAssign(b, e, ins.Dst, e.arg(ins.Args[0], ins.Elem))
			return nil
		}
		// prefer destination type (size_t i = 0 must stay uint64)
		ctx := e.regType[ins.Dst]
		if ctx == "" {
			ctx = e.regType[ins.Args[0]]
		}
		if ctx == "" {
			ctx = e.dom
		}
		// slice advance: p = p[1:]
		if ins.Sym == "ptr_adv1" && e.regPtr[ins.Dst] {
			e.line(b, "%s = %s[1:]\n", e.nameOf(ins.Dst), e.nameOf(ins.Args[0]))
			return nil
		}
		// pointer alias / offset cursor: share name with root (only for new non-param registers)
		if ins.Sym == "ptr_alias" && !e.isParam[ins.Dst] && e.regName[ins.Dst] == "" {
			srcn := e.nameOf(ins.Args[0])
			// address-of struct value → arg uses &v
			if !e.regPtr[ins.Args[0]] && ins.Sym == "ptr_alias" {
				e.isAddrOf[ins.Dst] = true
			}
			e.regName[ins.Dst] = srcn
			e.regPtr[ins.Dst] = true
			e.declared[ins.Dst] = true
			e.regType[ins.Dst] = e.regType[ins.Args[0]]
			e.elemIdx[ins.Dst] = e.elemIdx[ins.Args[0]]
			if e.stackArr[ins.Args[0]] {
				e.stackArr[ins.Dst] = true
			}
			return nil
		}
		// pointer alias: no new var (avoid unused slice temps)
		if len(ins.Args) > 0 && e.regPtr[ins.Args[0]] && ins.Sym != "ptr_adv1" && ins.Sym != "ptr_add" && !e.isParam[ins.Dst] {
			e.regName[ins.Dst] = e.nameOf(ins.Args[0])
			e.regPtr[ins.Dst] = true
			e.regType[ins.Dst] = e.regType[ins.Args[0]]
			e.declared[ins.Dst] = true
			e.elemIdx[ins.Dst] = e.elemIdx[ins.Args[0]]
			if e.stackArr[ins.Args[0]] {
				e.stackArr[ins.Dst] = true
			}
			delete(e.constImm, ins.Dst)
			return nil
		}
		e.regType[ins.Dst] = ctx
		writeAssign(b, e, ins.Dst, e.arg(ins.Args[0], ctx))
		e.regType[ins.Dst] = ctx
		delete(e.constImm, ins.Dst)
		if len(ins.Args) == 1 {
			e.valRoot[ins.Dst] = e.rootOf(ins.Args[0])
			if p, ok := e.xorPair[e.rootOf(ins.Args[0])]; ok {
				e.xorPair[ins.Dst] = p
			}
		}
	case ir.OpAdd, ir.OpSub, ir.OpMul, ir.OpDiv, ir.OpMod, ir.OpAnd, ir.OpOr, ir.OpXor, ir.OpShl, ir.OpShr:
		ctx := e.dom
		if t := e.regType[ins.Args[0]]; t != "" {
			ctx = t
		}
		if ins.Sym == "offslot" || ins.Elem == ir.TypUint64 {
			ctx = ir.TypUint64
		}
		// A declared local never narrows below its C width. Only widening is
		// applied — the front deliberately widens cursors and offsets, and
		// forcing the declared type on those broke every kernel.
		if t, ok := e.declType[ins.Dst]; ok && !e.regPtr[ins.Dst] && typeWidth(t) > typeWidth(ctx) {
			ctx = t
		}
		// ptr ± byteOff → reslice when front marked ptr_add
		if e.regPtr[ins.Args[0]] && (ins.Op == ir.OpAdd || ins.Op == ir.OpSub) && ins.Sym == "ptr_add" {
			off := wrapInt(e.arg(ins.Args[1], ir.TypInt))
			if ins.Op == ir.OpSub {
				// cannot reslice backward safely; keep name (best-effort)
				e.regName[ins.Dst] = e.nameOf(ins.Args[0])
				e.regPtr[ins.Dst] = true
				e.regType[ins.Dst] = e.regType[ins.Args[0]]
				e.declared[ins.Dst] = true
				delete(e.constImm, ins.Dst)
				break
			}
			// dead reslice temp (never read) → skip
			if e.f != nil && !isRead(ins.Dst, e.f.Stmts) {
				e.regName[ins.Dst] = e.nameOf(ins.Args[0])
				e.regPtr[ins.Dst] = true
				e.regType[ins.Dst] = e.regType[ins.Args[0]]
				e.declared[ins.Dst] = true
				e.suppress[ins.Dst] = true
				delete(e.constImm, ins.Dst)
				break
			}
			rhs := fmt.Sprintf("%s[%s:]", e.nameOf(ins.Args[0]), off)
			writeAssign(b, e, ins.Dst, rhs)
			e.regPtr[ins.Dst] = true
			e.regType[ins.Dst] = e.regType[ins.Args[0]]
			if e.regType[ins.Dst] == "" {
				e.regType[ins.Dst] = ir.TypUint8
			}
			e.elemIdx[ins.Dst] = e.elemIdx[ins.Args[0]]
			delete(e.constImm, ins.Dst)
			break
		}
		// other ptr+int: alias (offset in later loads via front fold)
		if e.regPtr[ins.Args[0]] && ins.Op == ir.OpAdd {
			e.regName[ins.Dst] = e.nameOf(ins.Args[0])
			e.regPtr[ins.Dst] = true
			e.regType[ins.Dst] = e.regType[ins.Args[0]]
			e.declared[ins.Dst] = true
			e.elemIdx[ins.Dst] = e.elemIdx[ins.Args[0]]
			if e.stackArr[ins.Args[0]] {
				e.stackArr[ins.Dst] = true
			}
			delete(e.constImm, ins.Dst)
			break
		}
		// `W - r`: remember it, a variable rotation is recognised by this shape
		if ins.Op == ir.OpSub {
			if c, ok := e.constImm[ins.Args[0]]; ok && c > 0 {
				if _, rIsConst := e.constImm[ins.Args[1]]; !rIsConst {
					e.subConst[ins.Dst] = subConstRec{c: c, v: ins.Args[1]}
				}
			}
		}
		// 0 - x  →  -int(x)  (C unary minus / negative loop bounds)
		if ins.Op == ir.OpSub {
			if imm, ok := e.constImm[ins.Args[0]]; ok && imm == 0 {
				// On an unsigned operand Go negates in the same width, so the
				// detour through int and back — uint32(-int(crc & 1)) for the
				// CRC mask — costs a reader two conversions and changes nothing.
				// Negating in the unsigned width would read better for a mask
				// — `-(crc & 1)` — but cannot be decided here: the operand is
				// still a register name at this point (inlining happens in the
				// later text passes), so a mask is indistinguishable from
				// murmur3's `-nblocks` loop counter, which needs a signed int.
				// Deciding it needs the type carried down to this site.
				rhs := fmt.Sprintf("-int(%s)", e.arg(ins.Args[1], ir.TypInt))
				writeAssign(b, e, ins.Dst, rhs)
				e.regType[ins.Dst] = ir.TypInt
				delete(e.constImm, ins.Dst)
				break
			}
		}
		// Const ⊗ Const → Imm (32-16, 64-24 for ROT only).
		// Restrict to Sub of small positives used as shift widths — full arith
		// fold poisoned siphash tail indices (off+6 with stale constImm).
		if ins.Op == ir.OpSub {
			if aImm, aOK := e.constImm[ins.Args[0]]; aOK {
				if bImm, bOK := e.constImm[ins.Args[1]]; bOK {
					if aImm >= 0 && bImm >= 0 && aImm <= 64 && bImm <= 64 {
						e.constImm[ins.Dst] = aImm - bImm
						e.regType[ins.Dst] = ctx
						break
					}
				}
			}
		}
		op := binOp(ins.Op)
		var rhs string
		if ins.Op == ir.OpShl || ins.Op == ir.OpShr {
			// C integer promotions: shifting a byte must widen before shift
			lctx := ctx
			if t := e.regType[ins.Args[0]]; t == ir.TypUint8 || t == "" {
				if e.dom == ir.TypUint32 || e.dom == ir.TypUint64 {
					lctx = e.dom
				} else {
					lctx = ir.TypUint32
				}
			} else if t != "" {
				lctx = t
			}
			// large shifts: widen to u64 (e.g. (u32)<<32 in load64)
			rImm, rIsImm := e.constImm[ins.Args[1]]
			if !rIsImm {
				// try parse from name? no
			}
			if rIsImm && rImm >= 32 {
				lctx = ir.TypUint64
			}
			// also widen if right is bare const 32 appearing as arg without constImm (Call path)
			if lctx == ir.TypUint32 && e.dom == ir.TypUint64 {
				lctx = ir.TypUint64
			}
			rhs = fmt.Sprintf("%s %s %s", e.arg(ins.Args[0], lctx), op, e.arg(ins.Args[1], ir.TypUint8))
			ctx = lctx
			if rIsImm {
				e.shiftDef[ins.Dst] = shiftRec{op: ins.Op, src: ins.Args[0], amt: rImm, typ: lctx}
			} else {
				e.shiftDef[ins.Dst] = shiftRec{op: ins.Op, src: ins.Args[0], typ: lctx, amtReg: ins.Args[1], amtVar: true}
			}
		} else if ins.Op == ir.OpOr || ins.Op == ir.OpXor {
			// ROT peephole: (x<<k)|(x>>(W-k)) or (x<<k)^(x>>(W-k)) → bits.RotateLeftW(x, k)
			if rot, ok := tryRotateLeft(e, ins); ok {
				e.needBits = true
				e.regType[ins.Dst] = rot.typ
				writeAssign(b, e, ins.Dst, rot.rhs)
				delete(e.constImm, ins.Dst)
				break
			}
			t0, t1 := e.regType[ins.Args[0]], e.regType[ins.Args[1]]
			if t0 != "" {
				ctx = t0
			}
			if t0 == ir.TypUint64 || t1 == ir.TypUint64 {
				ctx = ir.TypUint64
			}
			// track a^b pairs so ROTR's re-xor of the same operands still folds
			if ins.Op == ir.OpXor && len(ins.Args) == 2 {
				a, b := e.rootOf(ins.Args[0]), e.rootOf(ins.Args[1])
				if a > b {
					a, b = b, a
				}
				e.xorPair[ins.Dst] = [2]ir.Value{a, b}
				e.valRoot[ins.Dst] = ins.Dst
			}
			rhs = fmt.Sprintf("%s %s %s", e.arg(ins.Args[0], ctx), op, e.arg(ins.Args[1], ctx))
		} else if e.regPtr[ins.Args[0]] && ins.Op == ir.OpAdd {
			p := e.nameOf(ins.Args[0])
			off := e.arg(ins.Args[1], ir.TypInt)
			rhs = fmt.Sprintf("%s[%s:]", p, off)
			e.regPtr[ins.Dst] = true
			e.elemIdx[ins.Dst] = true
			e.regType[ins.Dst] = e.regType[ins.Args[0]]
		} else {
			// Prefer left operand type (C assignment context).
			// add/sub: if either side is int (signed loop index / negative off), keep int
			// so ptr offsets like nblocks*4 + i*4 with i<0 stay correct.
			// or/and/xor: widen to u64 if either side is u64 (load64 pattern)
			t0, t1 := e.regType[ins.Args[0]], e.regType[ins.Args[1]]
			if t0 != "" {
				ctx = t0
			}
			if (ins.Op == ir.OpAdd || ins.Op == ir.OpSub || ins.Op == ir.OpMul || ins.Op == ir.OpOr || ins.Op == ir.OpAnd || ins.Op == ir.OpXor) && (t0 == ir.TypUint64 || t1 == ir.TypUint64) {
				ctx = ir.TypUint64
			}
			if (ins.Op == ir.OpAdd || ins.Op == ir.OpSub || ins.Op == ir.OpMul || ins.Op == ir.OpOr || ins.Op == ir.OpAnd || ins.Op == ir.OpXor) && (t0 == ir.TypInt64 || t1 == ir.TypInt64) {
				ctx = ir.TypInt64
			}
			// x + 0 / 0 + x → x (never for offSlot bumps — loop-carried)
			if ins.Op == ir.OpAdd && ins.Sym != "offslot" && !e.noConstArg[ins.Args[0]] && !e.noConstArg[ins.Args[1]] {
				if imm, ok := e.constImm[ins.Args[1]]; ok && imm == 0 {
					e.regType[ins.Dst] = ctx
					if imm2, ok2 := e.constImm[ins.Args[0]]; ok2 {
						// const + 0 → const only
						e.constImm[ins.Dst] = imm2
						break
					}
					writeAssign(b, e, ins.Dst, e.arg(ins.Args[0], ctx))
					delete(e.constImm, ins.Dst)
					break
				}
				if imm, ok := e.constImm[ins.Args[0]]; ok && imm == 0 {
					e.regType[ins.Dst] = ctx
					if imm2, ok2 := e.constImm[ins.Args[1]]; ok2 {
						e.constImm[ins.Dst] = imm2
						break
					}
					writeAssign(b, e, ins.Dst, e.arg(ins.Args[1], ctx))
					delete(e.constImm, ins.Dst)
					break
				}
			}
			// offSlot arithmetic kills stale const on cursor
			if ins.Sym == "offslot" {
				delete(e.constImm, ins.Args[0])
				delete(e.constImm, ins.Dst)
				e.noConstArg[ins.Args[0]] = true
				e.noConstArg[ins.Dst] = true
			}
			// c * 0 / 0 * c → constImm only (Add 0+x folds; no dead v=0)
			if ins.Op == ir.OpMul {
				if imm, ok := e.constImm[ins.Args[0]]; ok && imm == 0 {
					e.regType[ins.Dst] = ctx
					e.constImm[ins.Dst] = 0
					break
				}
				if imm, ok := e.constImm[ins.Args[1]]; ok && imm == 0 {
					e.regType[ins.Dst] = ctx
					e.constImm[ins.Dst] = 0
					break
				}
			}
			// (x/k)*k with k power-of-two → x &^ (k-1)  (byte align down)
			if ins.Op == ir.OpMul {
				if k, ok := e.constImm[ins.Args[1]]; ok && k > 1 && k&(k-1) == 0 {
					if di, ok := e.divInfo[ins.Args[0]]; ok && di.k == k {
						mask := e.argConst(k-1, ctx)
						rhs = fmt.Sprintf("%s &^ %s", e.arg(di.src, ctx), mask)
						e.regType[ins.Dst] = ctx
						writeAssign(b, e, ins.Dst, rhs)
						delete(e.constImm, ins.Dst)
						break
					}
				}
				if k, ok := e.constImm[ins.Args[0]]; ok && k > 1 && k&(k-1) == 0 {
					if di, ok := e.divInfo[ins.Args[1]]; ok && di.k == k {
						mask := e.argConst(k-1, ctx)
						rhs = fmt.Sprintf("%s &^ %s", e.arg(di.src, ctx), mask)
						e.regType[ins.Dst] = ctx
						writeAssign(b, e, ins.Dst, rhs)
						delete(e.constImm, ins.Dst)
						break
					}
				}
			}
			// record x/k for later fold
			if ins.Op == ir.OpDiv {
				if k, ok := e.constImm[ins.Args[1]]; ok && k > 0 {
					e.divInfo[ins.Dst] = divRec{src: ins.Args[0], k: k}
				}
			}
			if e.suppress[ins.Dst] {
				e.regType[ins.Dst] = ctx
				delete(e.constImm, ins.Dst)
				break
			}
			tReg := e.regType[ins.Args[0]]
			goT := goType(tReg)
			if strings.HasPrefix(goT, "[]") && ins.Op == ir.OpAdd {
				rhs = fmt.Sprintf("%s[int(%s):]", e.arg(ins.Args[0], tReg), e.arg(ins.Args[1], ir.TypInt))
				e.regType[ins.Dst] = tReg
				writeAssign(b, e, ins.Dst, rhs)
				delete(e.constImm, ins.Dst)
				break
			}
			arg0 := e.arg(ins.Args[0], ctx)
			arg1 := e.arg(ins.Args[1], ctx)
			// C: & | ^ bind looser than << >> ; Go: same precedence, left-assoc.
			// Parenthesize so IR tree wins over Go text precedence.
			if (op == "&" || op == "|" || op == "^") && (strings.Contains(arg1, ">>") || strings.Contains(arg1, "<<")) {
				if !strings.HasPrefix(arg1, "(") || !strings.HasSuffix(arg1, ")") {
					arg1 = "(" + arg1 + ")"
				}
			}
			if (op == "<<" || op == ">>") && strings.ContainsAny(arg0, "&|^") {
				if !strings.HasPrefix(arg0, "(") || !strings.HasSuffix(arg0, ")") {
					arg0 = "(" + arg0 + ")"
				}
			}
			rhs = fmt.Sprintf("%s %s %s", arg0, op, arg1)
		}
		e.regType[ins.Dst] = ctx
		writeAssign(b, e, ins.Dst, rhs)
		delete(e.constImm, ins.Dst)
	case ir.OpAlloca:
		if strings.HasPrefix(ins.Sym, "struct_init:") {
			parts := strings.SplitN(ins.Sym[len("struct_init:"):], ":", 3)
			if len(parts) == 3 {
				sname := exportName(parts[0])
				cName := sanitizeIdent(parts[1])
				initCSV := parts[2]
				nm := e.nameOf(ins.Dst)
				if cName != "" {
					nm = cName
				}
				e.line(b, "var %s = %s{%s}\n", nm, sname, formatInitCSV(initCSV, ""))
				e.declared[ins.Dst] = true
				e.regName[ins.Dst] = nm
				e.regType[ins.Dst] = ins.Elem
				return nil
			}
		}
		if strings.HasPrefix(ins.Sym, "struct:") {
			sname := exportName(ins.Sym[len("struct:"):])
			e.line(b, "var %s %s\n", e.nameOf(ins.Dst), sname)
			e.declared[ins.Dst] = true
			e.regName[ins.Dst] = e.nameOf(ins.Dst)
			e.regType[ins.Dst] = ins.Elem
			// addressable struct; treat as pointer-compatible via &
			return nil
		}
		e.lastGlobalName = ""
		e.lastGlobalLen = 0
		n := ins.Imm
		elem := goType(ins.Elem)
		if elem == "" {
			elem = "uint8"
		}
		nm := e.nameOf(ins.Dst)
		initVal := ""
		if strings.HasPrefix(ins.Sym, "init:") {
			initData := ins.Sym[len("init:"):]
			initCSV := initData
			if idx := strings.Index(initData, ":"); idx > 0 {
				cName := sanitizeIdent(initData[:idx])
				initCSV = initData[idx+1:]
				if cName != "" {
					nm = cName
				}
			}
			if initCSV == "0" || initCSV == "0}" {
				initVal = fmt.Sprintf("[%d]%s{}", n, elem)
			} else {
				initVal = fmt.Sprintf("[%d]%s{%s}", n, elem, formatInitCSV(initCSV, ins.Elem))
			}
		}
		if initVal != "" {
			e.line(b, "var %s = %s\n", nm, initVal)
		} else {
			e.line(b, "var %s [%d]%s\n", nm, n, elem)
		}
		e.stackArr[ins.Dst] = true
		e.declared[ins.Dst] = true
		e.regName[ins.Dst] = nm
		e.regPtr[ins.Dst] = true
		e.regType[ins.Dst] = ins.Elem
		e.elemIdx[ins.Dst] = true
		return nil
	case ir.OpField:
		// dst = arg0.Field  (pointer or value); Imm=arrayLen if array field; Imm<0 = pointer field
		base := e.nameOf(ins.Args[0])
		field := exportName(ins.Sym)
		rhs := fmt.Sprintf("%s.%s", base, field)
		if ins.Imm > 0 || ins.Imm < 0 {
			e.elemIdx[ins.Dst] = true
			e.regPtr[ins.Dst] = true
		}
		if ins.Elem != "" {
			e.regType[ins.Dst] = ins.Elem
		} else {
			e.regType[ins.Dst] = ir.TypUint8
		}
		e.regName[ins.Dst] = rhs
		writeAssign(b, e, ins.Dst, rhs)
		delete(e.constImm, ins.Dst)
	case ir.OpFStore:
		base := e.nameOf(ins.Args[0])
		field := exportName(ins.Sym)
		ctx := ins.Elem
		if ctx == "" {
			ctx = e.regType[ins.Args[1]]
		}
		e.line(b, "%s.%s = %s\n", base, field, e.arg(ins.Args[1], ctx))
		killCSEBase(e, base)
	case ir.OpNot:
		ctx := e.regType[ins.Args[0]]
		if ctx == "" {
			ctx = e.dom
		}
		writeAssign(b, e, ins.Dst, "^"+e.arg(ins.Args[0], ctx))
		e.regType[ins.Dst] = ctx
		delete(e.constImm, ins.Dst)
	case ir.OpLoad:
		elem := ins.Elem
		if (elem == "" || elem == ir.TypUint8) && e.regType[ins.Args[0]] != "" && e.regType[ins.Args[0]] != ir.TypUint8 {
			elem = e.regType[ins.Args[0]]
		}
		if elem == "" {
			elem = e.regType[ins.Args[0]]
		}
		var rhs string
		if len(ins.Args) == 1 {
			p := ins.Args[0]
			if e.regPtr[p] {
				if e.scalarPtr[p] {
					rhs = "*" + e.nameOf(p)
				} else if e.elemIdx[p] || e.regType[p] == ir.TypUint32 || e.regType[p] == ir.TypUint64 {
					rhs = e.nameOf(p) + "[0]"
				} else if elem == ir.TypUint32 {
					rhs = fmt.Sprintf("binary.LittleEndian.Uint32(%s[0:])", e.nameOf(p))
					e.needBinary = true
				} else {
					rhs = fmt.Sprintf("uint32(%s[0])", e.nameOf(p))
					elem = ir.TypUint32
				}
			} else {
				rhs = "*" + e.nameOf(p)
			}
		} else {
			base := e.nameOf(ins.Args[0])
			idxa := e.arg(ins.Args[1], ir.TypInt)
			idx := wrapInt(idxa)
			baseT := e.regType[ins.Args[0]]
			// element index only when load elem matches base element type
			sameElem := e.elemIdx[ins.Args[0]] && (elem == baseT || (elem == ir.TypUint8 && (baseT == "" || baseT == ir.TypUint8)))
			// Typed word arrays (u32/u64/int tables): always element index, never LE byte view.
			wordArr := baseT == ir.TypUint64 || baseT == ir.TypUint32 || baseT == ir.TypInt || baseT == ir.TypInt64
			if sameElem || (wordArr && (elem == baseT || elem == "" || elem == ir.TypUint64 || elem == ir.TypUint32)) {
				rhs = fmt.Sprintf("%s[%s]", base, idx)
				if elem == "" {
					elem = baseT
				}
			} else if elem == ir.TypUint64 {
				// byte-oriented buffer
				rhs = fmt.Sprintf("binary.LittleEndian.Uint64(%s[%s:])", base, idx)
				e.needBinary = true
			} else if elem == ir.TypUint32 {
				if wordArr {
					rhs = fmt.Sprintf("%s[%s]", base, idx)
				} else {
					rhs = fmt.Sprintf("binary.LittleEndian.Uint32(%s[%s:])", base, idx)
					e.needBinary = true
				}
			} else {
				rhs = fmt.Sprintf("%s[%s]", base, idx)
				if elem == "" {
					elem = ir.TypUint8
				}
				targetT := e.regType[ins.Dst]
				if targetT != "" && targetT != ir.TypUint8 && !e.regPtr[ins.Dst] {
					rhs = fmt.Sprintf("%s(%s[%s])", goType(targetT), base, idx)
					elem = targetT
				}
			}
		}
		e.regPtr[ins.Dst] = false
		delete(e.regName, ins.Dst)
		e.regType[ins.Dst] = elem
		writeAssign(b, e, ins.Dst, rhs)
		delete(e.constImm, ins.Dst)
		// load alias key for ROT re-load of same slot (ptr or base+idx)
		switch len(ins.Args) {
		case 1:
			e.loadKey[ins.Dst] = [2]ir.Value{e.rootOf(ins.Args[0]), 0}
			e.valRoot[ins.Dst] = ins.Dst
		case 2:
			if imm, ok := e.constImm[ins.Args[1]]; ok {
				e.loadKey[ins.Dst] = [2]ir.Value{e.rootOf(ins.Args[0]), ir.Value(imm)}
			} else {
				e.loadKey[ins.Dst] = [2]ir.Value{e.rootOf(ins.Args[0]), e.rootOf(ins.Args[1])}
			}
			e.valRoot[ins.Dst] = ins.Dst
		}
	case ir.OpStore:
		elem := ins.Elem
		if t := e.regType[ins.Args[0]]; t != "" && t != ir.TypUint8 {
			elem = t
		}
		if (elem == "" || elem == ir.TypUint8) && e.regType[ins.Args[0]] != "" && e.regType[ins.Args[0]] != ir.TypUint8 {
			if t := e.regType[ins.Args[len(ins.Args)-1]]; t != "" && t != ir.TypUint8 {
				elem = t
			}
		}
		if elem == "" {
			elem = e.regType[ins.Args[0]]
		}
		// typed []T (elemIdx or regType wide on ptr param) → element assign; []byte + wide → LE
		typedSlice := e.elemIdx[ins.Args[0]] || e.regType[ins.Args[0]] == ir.TypUint32 || e.regType[ins.Args[0]] == ir.TypUint64
		baseNm := e.nameOf(ins.Args[0])
		if len(ins.Args) == 2 {
			if e.scalarPtr[ins.Args[0]] {
				e.line(b, "*%s = %s\n", baseNm, e.arg(ins.Args[1], elem))
			} else if !typedSlice && elem == ir.TypUint64 {
				e.line(b, "binary.LittleEndian.PutUint64(%s[0:], %s)\n", baseNm, e.arg(ins.Args[1], ir.TypUint64))
				e.needBinary = true
			} else if !typedSlice && elem == ir.TypUint32 {
				e.line(b, "binary.LittleEndian.PutUint32(%s[0:], %s)\n", baseNm, e.arg(ins.Args[1], ir.TypUint32))
				e.needBinary = true
			} else {
				e.line(b, "%s[0] = %s\n", baseNm, e.arg(ins.Args[1], elem))
			}
		} else if len(ins.Args) == 3 {
			idx := wrapInt(e.arg(ins.Args[1], ir.TypInt))
			// idx is already byte-scaled by front for wide stores on []byte
			if !typedSlice && elem == ir.TypUint64 {
				e.line(b, "binary.LittleEndian.PutUint64(%s[%s:], %s)\n", baseNm, idx, e.arg(ins.Args[2], ir.TypUint64))
				e.needBinary = true
			} else if !typedSlice && elem == ir.TypUint32 {
				e.line(b, "binary.LittleEndian.PutUint32(%s[%s:], %s)\n", baseNm, idx, e.arg(ins.Args[2], ir.TypUint32))
				e.needBinary = true
			} else {
				e.line(b, "%s[%s] = %s\n", baseNm, idx, e.arg(ins.Args[2], elem))
			}
		} else {
			return fmt.Errorf("emit: store arity")
		}
		// kill CSE of loads from this base (chacha *a+=*b then *d^=*a must reload a)
		killCSEBase(e, baseNm)
	case ir.OpReturn:
		e.lines(b, "return")
		if len(ins.Args) > 0 {
			b.WriteByte(' ')
			ctx := e.f.Result
			if ctx == "" || ctx == ir.TypVoid {
				ctx = e.dom
			}
			if ctx == "" || ctx == ir.TypVoid {
				ctx = e.regType[ins.Args[0]]
			}
			n := e.nameOf(ins.Args[0])
			if _, ok := e.constImm[ins.Args[0]]; ok {
				b.WriteString(e.arg(ins.Args[0], ctx))
			} else if ctx != "" && ctx != ir.TypInt && !e.regPtr[ins.Args[0]] {
				// force cast to result type
				b.WriteString(fmt.Sprintf("%s(%s)", goType(ctx), n))
			} else {
				b.WriteString(e.arg(ins.Args[0], ctx))
			}
		}
		b.WriteString("\n")
	case ir.OpCall:
		if ins.Sym == "__select" && len(ins.Args) == 3 {
			ctx := e.regType[ins.Args[1]]
			if ctx == "" {
				ctx = e.regType[ins.Args[2]]
			}
			if ctx == "" {
				ctx = e.dom
			}
			rhs := fmt.Sprintf("func() %s { if (%s) != 0 { return %s }; return %s }()", goType(ctx), e.arg(ins.Args[0], ir.TypInt), e.arg(ins.Args[1], ctx), e.arg(ins.Args[2], ctx))
			writeAssign(b, e, ins.Dst, rhs)
			e.regType[ins.Dst] = ctx
			delete(e.constImm, ins.Dst)
			return nil
		}
		if (strings.HasPrefix(ins.Sym, "__cmp_") || strings.HasPrefix(ins.Sym, "_cmp_")) && len(ins.Args) == 2 {
			op := ins.Sym
			if strings.HasPrefix(op, "__cmp_") {
				op = strings.TrimPrefix(op, "__cmp_")
			} else {
				op = strings.TrimPrefix(op, "_cmp_")
			}
			if op == "_" || op == "" {
				op = "=="
			}
			// pointer vs 0/NULL
			if e.regPtr[ins.Args[0]] || e.regPtr[ins.Args[1]] {
				var pside, zside ir.Value
				if e.regPtr[ins.Args[0]] {
					pside, zside = ins.Args[0], ins.Args[1]
				} else {
					pside, zside = ins.Args[1], ins.Args[0]
				}
				pn := e.nameOf(pside)
				// C NULL check on []byte / slices
				var rhs string
				if isUsedAsCond(e.f, ins.Dst) || e.forceCondBool {
					switch op {
					case "==":
						rhs = fmt.Sprintf("%s == nil", pn)
					case "!=":
						rhs = fmt.Sprintf("%s != nil", pn)
					default:
						rhs = "true"
					}
					writeAssign(b, e, ins.Dst, rhs)
					e.regType[ins.Dst] = ir.TypBool
				} else {
					switch op {
					case "==":
						rhs = fmt.Sprintf("func() int { if %s == nil { return 1 }; return 0 }()", pn)
					case "!=":
						rhs = fmt.Sprintf("func() int { if %s != nil { return 1 }; return 0 }()", pn)
					default:
						rhs = "1"
					}
					writeAssign(b, e, ins.Dst, rhs)
					e.regType[ins.Dst] = ir.TypInt
				}
				_ = zside
				delete(e.constImm, ins.Dst)
				return nil
			}
			ctx := e.regType[ins.Args[0]]
			if ctx == "" {
				ctx = e.regType[ins.Args[1]]
			}
			if ctx == "" {
				ctx = e.dom
			}
			l, r := e.arg(ins.Args[0], ctx), e.arg(ins.Args[1], ctx)
			var rhs string
			if isUsedAsCond(e.f, ins.Dst) || e.forceCondBool {
				if (op == "!=" || op == "==") && (r == "0" || isZeroLit(r)) && (e.regType[ins.Args[0]] == ir.TypBool || isBoolExpr(l)) {
					if op == "!=" {
						rhs = fmt.Sprintf("(%s)", l)
					} else {
						rhs = fmt.Sprintf("!(%s)", l)
					}
				} else {
					switch op {
					case "&&":
						rhs = fmt.Sprintf("(%s) && (%s)", e.toBoolStr(ins.Args[0], l), e.toBoolStr(ins.Args[1], r))
					case "||":
						rhs = fmt.Sprintf("(%s) || (%s)", e.toBoolStr(ins.Args[0], l), e.toBoolStr(ins.Args[1], r))
					default:
						rhs = fmt.Sprintf("(%s) %s (%s)", l, op, r)
					}
				}
				writeAssign(b, e, ins.Dst, rhs)
				e.regType[ins.Dst] = ir.TypBool
				delete(e.constImm, ins.Dst)
				return nil
			} else {
				switch op {
				case "&&":
					rhs = fmt.Sprintf("func() int { if %s && %s { return 1 }; return 0 }()", e.toBoolStr(ins.Args[0], l), e.toBoolStr(ins.Args[1], r))
				case "||":
					rhs = fmt.Sprintf("func() int { if %s || %s { return 1 }; return 0 }()", e.toBoolStr(ins.Args[0], l), e.toBoolStr(ins.Args[1], r))
				default:
					rhs = fmt.Sprintf("func() int { if (%s) %s (%s) { return 1 }; return 0 }()", l, op, r)
				}
				writeAssign(b, e, ins.Dst, rhs)
				e.regType[ins.Dst] = ir.TypInt
				delete(e.constImm, ins.Dst)
				return nil
			}
		}
		args := make([]string, len(ins.Args))
		callSym := baseCallSym(ins.Sym)
		var callee *ir.Func
		if e.callees != nil {
			callee = e.callees[callSym]
			if callee == nil {
				callee = e.callees[strings.ToLower(callSym)]
			}
		}
		// crypto_wipe: range zeroing for slices/arrays, skip for struct pointers
		if (callSym == "crypto_wipe" || callSym == "Crypto_wipe") && len(ins.Args) >= 1 {
			a0 := ins.Args[0]
			nm := e.nameOf(a0)
			// Barrier: any alias in regName that reads nm[ or nm must be materialized before wipe
			if !e.hoist {
				regKeys := make([]ir.Value, 0, len(e.regName))
				for r := range e.regName {
					regKeys = append(regKeys, r)
				}
				sort.Slice(regKeys, func(i, j int) bool { return regKeys[i] < regKeys[j] })
				for _, r := range regKeys {
					alias := e.regName[r]
					if (strings.Contains(alias, nm+"[") || strings.Contains(alias, nm+" ")) && !e.emitted[r] {
						rNm := fmt.Sprintf("v%d", int(r))
						if alias != rNm {
							e.line(b, "%s := %s\n", rNm, alias)
							e.regName[r] = rNm
							e.emitted[r] = true
							e.declared[r] = true
						}
					}
				}
			}
			st := e.regType[a0]
			if e.elemIdx[a0] || st == ir.TypUint8 || st == ir.TypUint32 || st == ir.TypUint64 || st == ir.TypInt {
				e.line(b, "for _i := range %s { %s[_i] = 0 }\n", nm, nm)
			} else {
				e.line(b, "_ = %s // wipe skipped struct\n", nm)
			}
			return nil
		}
		for i, a := range ins.Args {
			if callee != nil && i < len(callee.Params) {
				p := callee.Params[i]
				ctx := p.Type
				if p.StructName != "" || (p.Ptr && isStructTypeName(string(p.Type))) {
					argStr := e.arg(a, ctx)
					if !strings.HasPrefix(argStr, "&") && !e.regPtr[a] {
						argStr = "&" + argStr
					}
					args[i] = argStr
					continue
				}
				if p.Ptr || p.ArrayLen > 0 {
					// NULL / 0 → nil for slice params
					if imm, ok := e.constImm[a]; ok && imm == 0 {
						if p.ArrayLen == 0 && (p.Type == ir.TypUint32 || p.Type == ir.TypUint64) {
							args[i] = "nil"
						} else {
							args[i] = "nil"
						}
						continue
					}
					// callee wants *T only when that param is scalar-only in callee body
					if p.ArrayLen == 0 && (p.Type == ir.TypUint32 || p.Type == ir.TypUint64) &&
						ptrUsedAsScalarOnly(callee, p.Reg) {
						if e.scalarPtr[a] {
							args[i] = e.nameOf(a)
						} else {
							n := e.nameOf(a)
							if strings.HasPrefix(n, "&") {
								args[i] = n
							} else if e.regPtr[a] || e.elemIdx[a] {
								args[i] = "&" + n + "[0]"
							} else {
								args[i] = "&" + n
							}
						}
						continue
					}
					ctx = e.regType[a]
					if ctx == "" {
						ctx = e.dom
					}
					args[i] = e.arg(a, ctx)
					continue
				}
				args[i] = e.arg(a, ctx)
			} else {
				// prefer arg's own type to avoid bogus uint8(count)
				ctx := e.regType[a]
				if ctx == "" {
					ctx = e.dom
				}
				// shift amounts often need uint
				if (ins.Sym == "rotl32" || ins.Sym == "Rotl32" || ins.Sym == "rotr64") && i == 1 {
					ctx = ir.TypUint32
				}
				args[i] = e.arg(a, ctx)
			}
		}
		sym := resolveGoName(e, callSym)
		// libc-ish builtins without harvested body
		if bultin := emitBuiltinCall(callSym, args); bultin != "" {
			call := bultin
			low := strings.ToLower(callSym)
			voidBuiltin := low == "memset" || low == "memcpy" || low == "memmove"
			if ins.Dst == ir.NoVal {
				if !e.hoist {
					if voidBuiltin {
						e.line(b, "%s\n", call)
					} else {
						e.line(b, "_ = %s\n", call)
					}
				}
				return nil
			}
			// strchr returns []byte (nullable slice)
			if low == "strchr" {
				e.regType[ins.Dst] = ir.TypUint8
				e.regPtr[ins.Dst] = true
			} else {
				e.regType[ins.Dst] = e.dom
			}
			writeAssign(b, e, ins.Dst, call)
			delete(e.constImm, ins.Dst)
			return nil
		}
		call := sym + "(" + strings.Join(args, ", ") + ")"
		if ins.Dst == ir.NoVal {
			if !e.hoist {
				e.line(b, "%s\n", call)
			}
			return nil
		}
		retType := e.dom
		if callee, ok := e.callees[callSym]; ok && callee.Result != "" && callee.Result != ir.TypVoid {
			retType = callee.Result
		} else if callee, ok := e.callees[strings.ToLower(callSym)]; ok && callee.Result != "" && callee.Result != ir.TypVoid {
			retType = callee.Result
		}
		e.regType[ins.Dst] = retType
		writeAssign(b, e, ins.Dst, call)
		delete(e.constImm, ins.Dst)
	default:
		return fmt.Errorf("emit: op %v", ins.Op)
	}
	return nil
}

func writeAssign(b *strings.Builder, e *env, dst ir.Value, rhs string) {
	if e.suppress[dst] {
		return
	}
	orig := rhs
	// CSE: rewrite rhs to prior name holding same pure expr
	if prev, ok := e.cseExpr[rhs]; ok && prev != "" {
		rhs = prev
	}
	// single-write copy of single-write (or non-vreg) → pure alias, no emit
	if canPureAlias(e, dst, rhs) {
		e.regName[dst] = rhs
		e.declared[dst] = true
		return
	}
	nm := e.nameOf(dst)
	if e.hoist {
		if e.hoistTypes != nil {
			if t := e.regType[dst]; t != "" {
				e.hoistTypes[dst] = t
			}
		}
		// track CSE/name so later hoist sees aliases
		e.cseExpr[orig] = nm
		return
	}
	if rhs == nm {
		return
	}
	// pure rename only if dst never declared AND src is single-write
	// (multi-write src needs snapshot — postinc j++ / base64 dst[j++])
	if isSimpleIdent(rhs) && !e.declared[dst] && !strings.ContainsAny(rhs, ".[]") && canPureAlias(e, dst, rhs) {
		e.regName[dst] = rhs
		e.declared[dst] = true
		return
	}
	b.WriteString(e.pad())
	if !e.declared[dst] && !strings.ContainsAny(nm, ".[]&") {
		b.WriteString(nm)
		b.WriteString(" := ")
		e.declared[dst] = true
		e.emitted[dst] = true
		e.regName[dst] = nm
		b.WriteString(rhs)
		b.WriteString("\n")
		if e.f != nil && !isRead(dst, e.f.Stmts) {
			fmt.Fprintf(b, "%s_ = %s\n", e.pad(), nm)
		}
		e.cseExpr[orig] = nm
		return
	}
	if rhs == nm {
		return
	}
	e.emitted[dst] = true
	b.WriteString(nm)
	b.WriteString(" = ")
	b.WriteString(rhs)
	b.WriteString("\n")
	// kill CSE that depended on nm
	for k := range e.cseExpr {
		if strings.Contains(k, nm) {
			delete(e.cseExpr, k)
		}
	}
	e.cseExpr[orig] = nm
}

// ptrUsedAsScalarOnly reports whether reg is only deref'd at [0] / *p (no index/slice).
func ptrUsedAsScalarOnly(f *ir.Func, reg ir.Value) bool {
	if f == nil {
		return false
	}
	// aliases via ptr+0 still ok; indexed load/store or ptr_add with non-zero → slice
	var walk func([]ir.Stmt) bool
	walk = func(ss []ir.Stmt) bool {
		for _, s := range ss {
			check := func(ins ir.Instr) bool {
				switch ins.Op {
				case ir.OpLoad:
					if len(ins.Args) >= 1 && baseAliased(ins.Args[0], reg, f) {
						if len(ins.Args) >= 2 {
							return false // indexed
						}
					}
				case ir.OpStore:
					if len(ins.Args) >= 1 && baseAliased(ins.Args[0], reg, f) {
						if len(ins.Args) >= 3 {
							return false // indexed store
						}
					}
				case ir.OpAdd, ir.OpSub:
					if len(ins.Args) >= 1 && baseAliased(ins.Args[0], reg, f) && ins.Sym == "ptr_add" {
						return false
					}
				}
				return true
			}
			if s.Kind == ir.SKInstr {
				if !check(s.Ins) {
					return false
				}
			}
			for _, ins := range s.ForInit {
				if !check(ins) {
					return false
				}
			}
			for _, ins := range s.ForCondPrep {
				if !check(ins) {
					return false
				}
			}
			for _, ins := range s.ForPost {
				if !check(ins) {
					return false
				}
			}
			for _, ins := range s.SwitchPrep {
				if !check(ins) {
					return false
				}
			}
			if !walk(s.ThenBody) || !walk(s.ElseBody) || !walk(s.ForBody) || !walk(s.DoBody) {
				return false
			}
			for _, c := range s.SwitchCases {
				if !walk(c.Body) {
					return false
				}
			}
		}
		return true
	}
	return walk(f.Stmts)
}

func baseAliased(v, reg ir.Value, f *ir.Func) bool {
	if v == reg {
		return true
	}
	// cheap: only exact param match (ptr arithmetic creates new vregs checked via walk)
	_ = f
	return false
}

type rotResult struct {
	rhs string
	typ ir.TypeName
}

// tryRotateLeft matches (x<<k)|(x>>(W-k)) with W in {32,64}.
func tryRotateLeft(e *env, ins ir.Instr) (rotResult, bool) {
	if len(ins.Args) != 2 {
		return rotResult{}, false
	}
	l, okL := e.shiftDef[ins.Args[0]]
	r, okR := e.shiftDef[ins.Args[1]]
	if !okL || !okR {
		return rotResult{}, false
	}
	var shl, shr shiftRec
	switch {
	case l.op == ir.OpShl && r.op == ir.OpShr:
		shl, shr = l, r
	case l.op == ir.OpShr && r.op == ir.OpShl:
		shl, shr = r, l
	default:
		return rotResult{}, false
	}
	if !e.sameRotSrc(shl.src, shr.src) {
		return rotResult{}, false
	}
	if shl.amtVar || shr.amtVar {
		return e.tryRotateVariable(shl, shr)
	}
	typ := shl.typ
	if typ == "" {
		typ = shr.typ
	}
	var w int64
	switch typ {
	case ir.TypUint32:
		w = 32
	case ir.TypUint64:
		w = 64
	default:
		if shl.amt+shr.amt == 32 {
			w, typ = 32, ir.TypUint32
		} else if shl.amt+shr.amt == 64 {
			w, typ = 64, ir.TypUint64
		} else {
			return rotResult{}, false
		}
	}
	if shl.amt+shr.amt != w || shl.amt <= 0 || shl.amt >= w {
		return rotResult{}, false
	}
	src := e.arg(shl.src, typ)
	fn := "bits.RotateLeft32"
	if w == 64 {
		fn = "bits.RotateLeft64"
	}
	return rotResult{
		rhs: fmt.Sprintf("%s(%s, %d)", fn, src, shl.amt),
		typ: typ,
	}, true
}

// tryRotateVariable matches a rotation whose count is a value, not a literal:
// (x << r) | (x >> (W - r)) and its mirror. The width must come from the shifted
// operand's own type — reading it from the `W -` constant alone would happily
// fold a 32-bit rotation over a 64-bit value.
func (e *env) tryRotateVariable(shl, shr shiftRec) (rotResult, bool) {
	typ := shl.typ
	if typ == "" {
		typ = shr.typ
	}
	var w int64
	switch typ {
	case ir.TypUint32:
		w = 32
	case ir.TypUint64:
		w = 64
	default:
		return rotResult{}, false
	}

	fn := "bits.RotateLeft32"
	if w == 64 {
		fn = "bits.RotateLeft64"
	}
	src := e.arg(shl.src, typ)

	// left by r, right by (W - r) → rotate left by r
	if shl.amtVar && shr.amtVar {
		if rec, ok := e.subConst[shr.amtReg]; ok && rec.c == w && rec.v == shl.amtReg {
			return rotResult{
				rhs: fmt.Sprintf("%s(%s, int(%s))", fn, src, e.arg(shl.amtReg, ir.TypInt)),
				typ: typ,
			}, true
		}
		// right by r, left by (W - r) → rotate left by (W - r)
		if rec, ok := e.subConst[shl.amtReg]; ok && rec.c == w && rec.v == shr.amtReg {
			return rotResult{
				rhs: fmt.Sprintf("%s(%s, %d-int(%s))", fn, src, w, e.arg(shr.amtReg, ir.TypInt)),
				typ: typ,
			}, true
		}
	}
	return rotResult{}, false
}

func parseShiftVal(s string) (int64, error) {
	s = strings.TrimSpace(s)
	if strings.HasPrefix(s, "'") && strings.HasSuffix(s, "'") && len(s) == 3 {
		return int64(s[1]), nil
	}
	return strconv.ParseInt(s, 10, 64)
}

var rotOrPat = regexp.MustCompile(
	`\(+((?:\([^)]+\)|[^()|^]+)) << (?:uint8\()?(\d+|'[^']+')\)?\) [|^] \(((?:\([^)]+\)|[^()|^]+)) >> (?:uint8\()?(\d+|'[^']+')\)?\)+`,
)
var rotShrPat = regexp.MustCompile(
	`\(+((?:\([^)]+\)|[^()|^]+)) >> (?:uint8\()?(\d+|'[^']+')\)?\) [|^] \(((?:\([^)]+\)|[^()|^]+)) << (?:uint8\()?(\d+|'[^']+')\)?\)+`,
)

// foldRotateExprs rewrites (x<<k)|(x>>(W-k)) or (x>>k)^(x<<(W-k)) to bits.RotateLeftW.
func foldRotateExprs(block string) string {
	res := rotOrPat.ReplaceAllStringFunc(block, func(m string) string {
		sub := rotOrPat.FindStringSubmatch(m)
		if sub == nil {
			return m
		}
		x1 := strings.TrimSpace(sub[1])
		k1, err1 := parseShiftVal(sub[2])
		x2 := strings.TrimSpace(sub[3])
		k2, err2 := parseShiftVal(sub[4])
		if err1 != nil || err2 != nil {
			return m
		}
		if x1 != x2 || (k1+k2 != 32 && k1+k2 != 64) {
			return m
		}
		fn := "bits.RotateLeft32"
		if k1+k2 == 64 {
			fn = "bits.RotateLeft64"
		}
		return fmt.Sprintf("%s(%s, %d)", fn, x1, k1)
	})
	return rotShrPat.ReplaceAllStringFunc(res, func(m string) string {
		sub := rotShrPat.FindStringSubmatch(m)
		if sub == nil {
			return m
		}
		x1 := strings.TrimSpace(sub[1])
		k1, err1 := parseShiftVal(sub[2])
		x2 := strings.TrimSpace(sub[3])
		k2, err2 := parseShiftVal(sub[4])
		if err1 != nil || err2 != nil {
			return m
		}
		if x1 != x2 || (k1+k2 != 32 && k1+k2 != 64) {
			return m
		}
		fn := "bits.RotateLeft32"
		if k1+k2 == 64 {
			fn = "bits.RotateLeft64"
		}
		return fmt.Sprintf("%s(%s, %d)", fn, x1, k2)
	})
}

// castPairPat matches T1(T2(x) for scalar types; RE2 has no backreference, so the
// two names are compared by hand.
var castPairPat = regexp.MustCompile(`(int|int8|int16|int32|int64|uint|uint8|uint16|uint32|uint64|byte)\((int|int8|int16|int32|int64|uint|uint8|uint16|uint32|uint64|byte)\(`)

// dropDoubleCasts rewrites T(T(x)) to T(x). Converting a value to the type it
// already has is a no-op the C reader has to decode.
func dropDoubleCasts(block string) string {
	for {
		next := dropDoubleCastsOnce(block)
		if next == block {
			return block
		}
		block = next
	}
}

// negMaskPat matches uintW(-int(EXPR)), the shape a C mask `-(crc & 1)` takes
// once emitted through a signed intermediate.
var negMaskPat = regexp.MustCompile(`\b(uint8|uint16|uint32|uint64)\(-int\(`)

// foldNegatedMask rewrites uintW(-int(x & …)) to -(x & …). Go negates an
// unsigned value in its own width, which is exactly what the C mask means, so
// the signed detour and both conversions carry no information.
//
// Two guards keep this honest. The inner expression must be bitwise — murmur3
// negates a plain count to walk backwards from -nblocks, and that one needs its
// signed int. And it must contain a conversion to the same width, which is the
// only textual evidence that the expression is already that wide; without it,
// uint32(-int(u64expr)) and -(u64expr) differ.
func foldNegatedMask(block string) string {
	for {
		loc := negMaskPat.FindStringIndex(block)
		if loc == nil {
			return block
		}
		match := matchParens(block)
		if match == nil {
			return block
		}
		width := negMaskPat.FindStringSubmatch(block[loc[0]:loc[1]])[1]
		openOuter := loc[0] + len(width) // '(' of uintW(
		openInner := loc[1] - 1          // '(' of int(
		closeOuter, ok1 := match[openOuter]
		closeInner, ok2 := match[openInner]
		if !ok1 || !ok2 || closeInner != closeOuter-1 {
			return block // not the plain nesting: leave it alone
		}
		expr := block[openInner+1 : closeInner]
		if !strings.ContainsAny(expr, "&|^") || !strings.Contains(expr, width+"(") {
			return block
		}
		return block[:openOuter-len(width)] + "-(" + expr + ")" + block[closeOuter+1:]
	}
}

var (
	varDeclPat    = regexp.MustCompile(`^\s*var\s+([A-Za-z_][A-Za-z0-9_]*)\s+(u?int(?:8|16|32|64)?|byte)\s*$`)
	shortDeclPat  = regexp.MustCompile(`^\s*([A-Za-z_][A-Za-z0-9_]*)\s*:=\s*(u?int(?:8|16|32|64)?|byte)\(`)
	returnCastPat = regexp.MustCompile(`^(\s*return\s+)(u?int(?:8|16|32|64)?|byte)\((.*)\)\s*$`)
	assignPat     = regexp.MustCompile(`^\s*([A-Za-z_][A-Za-z0-9_]*)\s+=\s+(.*)$`)
	intLitPat     = regexp.MustCompile(`^-?(?:0[xX][0-9a-fA-F]+|\d+)$`)
	// `v59 := v10 * 16` takes v10's type
	derivedDeclPat = regexp.MustCompile(`^\s*([A-Za-z_][A-Za-z0-9_]*) := ([A-Za-z_][A-Za-z0-9_]*) [+\-*] \d+$`)
	// int(uint64(1)) is a literal wearing two coats
	nestedLitCastPat = regexp.MustCompile(`\b(u?int(?:8|16|32|64)?|byte)\((?:u?int(?:8|16|32|64)?|byte)\((\d+)\)\)`)
	// int(1) is an untyped constant already
	intLitCastPat = regexp.MustCompile(`\bint\((\d+)\)`)
)

// paramTypes maps each parameter name to its Go type, so a cast back to a
// parameter's own type can be recognised as a no-op.
func paramTypes(f *ir.Func) map[string]string {
	out := map[string]string{}
	for _, p := range f.Params {
		if p.Ptr || p.ArrayLen > 0 || p.StructName != "" {
			continue
		}
		if t := goType(p.Type); t != "" {
			out[sanitizeIdent(p.Name)] = t
		}
	}
	return out
}

// localTypes reads the block's own declarations: `var v2 uint64` and the short
// form `v12 := uint32(…)`, whose leading conversion fixes the type.
func localTypes(lines []string, seed map[string]string) map[string]string {
	types := map[string]string{}
	for k, v := range seed {
		types[k] = v
	}
	for _, ln := range lines {
		if m := varDeclPat.FindStringSubmatch(ln); m != nil {
			types[m[1]] = m[2]
			continue
		}
		if m := shortDeclPat.FindStringSubmatch(ln); m != nil {
			types[m[1]] = m[2]
			continue
		}
		// `v59 := v10 * 16` carries v10's type; blake derives its sigma index
		// this way, and without it the conversion around v59 survives.
		if m := derivedDeclPat.FindStringSubmatch(ln); m != nil {
			if t, ok := types[m[2]]; ok {
				types[m[1]] = t
			}
		}
	}
	return types
}

// dropIdentityCasts removes conversions that convert a value to the type it
// already has: `return uint64(v2)` on a uint64 result, and `v4 = v4 + uint64(1)`
// where the untyped literal takes v4's type anyway. A short declaration keeps
// its conversion — `x := 1` would be an int.
func dropIdentityCasts(block, retType string, params map[string]string) string {
	lines := strings.Split(block, "\n")
	types := localTypes(lines, params)
	for i, ln := range lines {
		if m := returnCastPat.FindStringSubmatch(ln); m != nil && m[2] == retType {
			inner := strings.TrimSpace(m[3])
			// `^v2` and `-v2` keep their operand's type
			bare := strings.TrimLeft(inner, "^-")
			if types[inner] == retType || types[bare] == retType || intLitPat.MatchString(inner) {
				lines[i] = m[1] + inner
				continue
			}
		}
		if m := assignPat.FindStringSubmatch(ln); m != nil {
			if t, ok := types[m[1]]; ok {
				ln = strings.Replace(ln, m[2], dropLitCastsOfType(m[2], t), 1)
			}
		}
		ln = nestedLitCastPat.ReplaceAllString(ln, "$1($2)")
		ln = intLitCastPat.ReplaceAllString(ln, "$1")
		ln = narrowIndexShiftMask(ln, types)
		ln = dropSelfCasts(ln, types)
		lines[i] = dropLitCastsInComparisons(ln, types)
	}
	return strings.Join(lines, "\n")
}

var (
	selfCastPat     = regexp.MustCompile(`\b(u?int(?:8|16|32|64)?|byte)\(([A-Za-z_][A-Za-z0-9_]*)\)`)
	selfCastExprPat = regexp.MustCompile(`\bint\(([A-Za-z_][A-Za-z0-9_]*) ([+\-*]) (\d+)\)`)
)

// dropSelfCasts removes a conversion to the type the value already carries.
// Index sites wrap unconditionally — `v7[int(v9)]` — which is noise once the
// counter is itself an int. Arithmetic keeps its parentheses: `int(v9 - 1) * 2`
// must not become `v9 - 1 * 2`.
func dropSelfCasts(ln string, types map[string]string) string {
	ln = selfCastPat.ReplaceAllStringFunc(ln, func(m string) string {
		sub := selfCastPat.FindStringSubmatch(m)
		if types[sub[2]] != sub[1] {
			return m
		}
		return sub[2]
	})
	return selfCastExprPat.ReplaceAllStringFunc(ln, func(m string) string {
		sub := selfCastExprPat.FindStringSubmatch(m)
		if types[sub[1]] != "int" {
			return m
		}
		return "(" + sub[1] + " " + sub[2] + " " + sub[3] + ")"
	})
}

// binLitCastPat matches `name <op> uint32(8)`: a converted literal facing a
// typed value, where the untyped form already takes the other side's type.
var binLitCastPat = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*) (<|>|<=|>=|==|!=|&|\||\^|\+|-|\*) (u?int(?:8|16|32|64)?|byte)\((-?(?:0[xX][0-9a-fA-F]+|\d+))\)`)

func dropLitCastsInComparisons(ln string, types map[string]string) string {
	return binLitCastPat.ReplaceAllStringFunc(ln, func(m string) string {
		sub := binLitCastPat.FindStringSubmatch(m)
		if types[sub[1]] != sub[3] {
			return m
		}
		return sub[1] + " " + sub[2] + " " + sub[4]
	})
}

var (
	forOpenPat    = regexp.MustCompile(`^(\s*)for \{$`)
	breakGuardPat = regexp.MustCompile(`^\s*if !\((.*)\) \{ break \}$`)
)

// hoistLoopGuards turns `for { if !(C) { break } … }` into `for C { … }`, and
// merges any guard immediately following into the same condition.
//
// Only guards that sit directly under the `for` are taken. cjson's loop reads
// `v15 := s[i]` between its guards and uses that value in the body: pulling the
// later guards up would either duplicate the load or leave the body without its
// value, so those stay where they are.
func hoistLoopGuards(block string) string {
	lines := strings.Split(block, "\n")
	out := make([]string, 0, len(lines))
	for i := 0; i < len(lines); i++ {
		open := forOpenPat.FindStringSubmatch(lines[i])
		if open == nil || i+1 >= len(lines) {
			out = append(out, lines[i])
			continue
		}
		var conds []string
		j := i + 1
		for j < len(lines) {
			g := breakGuardPat.FindStringSubmatch(lines[j])
			if g == nil {
				break
			}
			conds = append(conds, g[1])
			j++
		}
		if len(conds) == 0 {
			out = append(out, lines[i])
			continue
		}
		out = append(out, open[1]+"for "+strings.Join(conds, " && ")+" {")
		i = j - 1
	}
	return strings.Join(out, "\n")
}

var (
	snapshotPat = regexp.MustCompile(`^(\s*)([A-Za-z_][A-Za-z0-9_]*) := ([A-Za-z_][A-Za-z0-9_]*)$`)
	incPat      = regexp.MustCompile(`^\s*([A-Za-z_][A-Za-z0-9_]*) = ([A-Za-z_][A-Za-z0-9_]*) \+ 1$`)
)

// foldPostIncStore rewrites the three lines a C `dst[j++] = v` expands into:
//
//	v31 := v5
//	v5 = v5 + 1
//	dst[int(v31)] = …
//
// into `dst[int(v5)] = …` followed by `v5++`. The snapshot may have exactly one
// reader — the store's index — and the store must not touch the counter itself,
// or moving the increment ahead of it would change what is written.
func foldPostIncStore(block string) string {
	lines := strings.Split(block, "\n")
	out := make([]string, 0, len(lines))
	for i := 0; i < len(lines); i++ {
		snap := snapshotPat.FindStringSubmatch(lines[i])
		if snap == nil || i+2 >= len(lines) {
			out = append(out, lines[i])
			continue
		}
		pad, tmp, counter := snap[1], snap[2], snap[3]
		inc := incPat.FindStringSubmatch(lines[i+1])
		if inc == nil || inc[1] != counter || inc[2] != counter {
			out = append(out, lines[i])
			continue
		}
		store := lines[i+2]
		eq := strings.Index(store, " = ")
		if eq < 0 || !strings.Contains(store[:eq], "["+"int("+tmp+")") {
			out = append(out, lines[i])
			continue
		}
		// the counter must not appear in the stored value, and the snapshot
		// must be read nowhere else
		if identContains(store[eq+3:], counter) || countIdentUses(lines, tmp, i+2) > 0 {
			out = append(out, lines[i])
			continue
		}
		out = append(out, strings.Replace(store, "int("+tmp+")", "int("+counter+")", 1))
		out = append(out, pad+counter+"++")
		i += 2
	}
	return strings.Join(out, "\n")
}

// dropRedundantAlignMask strips `v &^ 7` / `v &^ uint64(7)` in slice indices.
// Safe when the induction is already a multiple of 8 (fast_xor bulk loop).
var alignMask7Pat = regexp.MustCompile(`int\(([A-Za-z_][A-Za-z0-9_]*)\s*&\^\s*(?:uint64\()?7\)?\)`)

func dropRedundantAlignMask(block string) string {
	return alignMask7Pat.ReplaceAllString(block, "int($1)")
}

// bceIndexLoops rewrites a simple
//
//	for i < n {
//	  ... x[i] ... y[i] ...
//	  i = i + 1
//	}
//
// into bound slices so the compiler can elide bounds checks (Vn / verify).
func bceIndexLoops(block string) string {
	lines := strings.Split(block, "\n")
	out := make([]string, 0, len(lines))
	forHdr := regexp.MustCompile(`^(\t*)for ([A-Za-z_][A-Za-z0-9_]*) < ([A-Za-z_][A-Za-z0-9_]*) \{$`)
	for i := 0; i < len(lines); i++ {
		h := forHdr.FindStringSubmatch(lines[i])
		if h == nil {
			out = append(out, lines[i])
			continue
		}
		pad, idx, lim := h[1], h[2], h[3]
		// collect body until matching closing brace at same indent
		j := i + 1
		var body []string
		for j < len(lines) {
			if lines[j] == pad+"}" {
				break
			}
			body = append(body, lines[j])
			j++
		}
		if j >= len(lines) {
			out = append(out, lines[i])
			continue
		}
		bodyText := strings.Join(body, "\n") + "\n"
		if !strings.Contains(bodyText, idx+" = "+idx+" + 1") && !strings.Contains(bodyText, idx+"++") {
			out = append(out, lines[i])
			continue
		}
		// only int counters (Vn); uint64 i < len_ must not become int via := 0
		declInt := false
		for _, prev := range out {
			if strings.Contains(prev, "var "+idx+" int") {
				declInt = true
				break
			}
		}
		if !declInt {
			out = append(out, lines[i])
			continue
		}
		// reject nested braces / multi-line complexity
		if strings.Count(bodyText, "{") != 0 {
			out = append(out, lines[i])
			continue
		}
		reIdx := regexp.MustCompile(`\b([A-Za-z_][A-Za-z0-9_]*)\[(?:int\()?` + regexp.QuoteMeta(idx) + `\)?\]`)
		found := map[string]bool{}
		for _, sm := range reIdx.FindAllStringSubmatch(bodyText, -1) {
			if sm[1] != idx {
				found[sm[1]] = true
			}
		}
		if len(found) < 1 || len(found) > 3 {
			out = append(out, lines[i])
			continue
		}
		var names []string
		for n := range found {
			names = append(names, n)
		}
		sort.Strings(names)
		out = append(out, pad+"{")
		for _, n := range names {
			out = append(out, fmt.Sprintf("%s\t_%s := %s[:%s]", pad, n, n, lim))
		}
		// reuse existing int counter — no shadowing
		out = append(out, pad+"\t"+idx+" = 0")
		out = append(out, fmt.Sprintf("%s\tfor %s < %s {", pad, idx, lim))
		incRe := regexp.MustCompile(`^\t*` + regexp.QuoteMeta(idx) + `\s*=\s*` + regexp.QuoteMeta(idx) + `\s*\+\s*1\s*$`)
		incRe2 := regexp.MustCompile(`^\t*` + regexp.QuoteMeta(idx) + `\+\+\s*$`)
		for _, ln := range body {
			if incRe.MatchString(ln) || incRe2.MatchString(ln) {
				continue
			}
			nl := ln
			for _, n := range names {
				nl = regexp.MustCompile(`\b`+regexp.QuoteMeta(n)+`\[`).ReplaceAllString(nl, "_"+n+"[")
			}
			if strings.HasPrefix(nl, pad) {
				nl = pad + "\t" + strings.TrimPrefix(nl, pad)
			}
			out = append(out, nl)
		}
		out = append(out, pad+"\t\t"+idx+"++")
		out = append(out, pad+"\t}")
		out = append(out, pad+"}")
		i = j // skip original body + closing brace
	}
	return strings.Join(out, "\n")
}

// countIdentUses counts reads of name outside line skip.
func countIdentUses(lines []string, name string, skip int) int {
	n := 0
	for i, ln := range lines {
		if i == skip {
			continue
		}
		if snap := snapshotPat.FindStringSubmatch(ln); snap != nil && snap[2] == name {
			continue // its own definition
		}
		if identContains(ln, name) {
			n++
		}
	}
	return n
}

// widenedIndexPat matches int(uint64(x) >> k & uint64(m)): an index computed in
// a wider type than the value it reads from.
var widenedIndexPat = regexp.MustCompile(`int\((u?int(?:8|16|32|64)?)\(([A-Za-z_][A-Za-z0-9_]*)\) >> (\d+) & (u?int(?:8|16|32|64)?)\((\d+)\)\)`)

// narrowIndexShiftMask keeps a shift-and-mask index in the value's own width.
// Widening before a right shift cannot bring in bits that were not there, so
// int(uint64(v12) >> 18 & uint64(63)) is int((v12 >> 18) & 63) whenever v12 is
// narrower than the shift would need — checked against its declared type.
func narrowIndexShiftMask(block string, types map[string]string) string {
	return widenedIndexPat.ReplaceAllStringFunc(block, func(m string) string {
		sub := widenedIndexPat.FindStringSubmatch(m)
		wide, name, shift, maskType, mask := sub[1], sub[2], sub[3], sub[4], sub[5]
		if wide != maskType {
			return m // both sides must have been widened the same way
		}
		t, ok := types[name]
		if !ok || t == wide {
			return m // no declared type, or no widening happened
		}
		w := typeWidth(ir.TypeName(t))
		s, err := strconv.Atoi(shift)
		if err != nil || w == 0 || s >= w {
			return m
		}
		return fmt.Sprintf("int((%s >> %s) & %s)", name, shift, mask)
	})
}

// dropLitCastsOfType unwraps T(<literal>) when T is the assignment's own type.
func dropLitCastsOfType(rhs, typ string) string {
	pat := regexp.MustCompile(`\b` + typ + `\((-?(?:0[xX][0-9a-fA-F]+|\d+))\)`)
	return pat.ReplaceAllString(rhs, "$1")
}

// shiftCountPat matches an explicitly typed shift count: `x >> uint8(16)`.
var shiftCountPat = regexp.MustCompile(`(<<|>>) (?:u?int(?:8|16|32|64)?|byte)\((\d+)\)`)

// bareShiftCounts drops the conversion around a literal shift count. Go takes
// any integer type on the right of a shift, so uint8(16) says nothing 16 does
// not already say.
func bareShiftCounts(block string) string {
	return shiftCountPat.ReplaceAllString(block, "$1 $2")
}

// truncatingCast lists the outer types that keep only their own width, so an
// intermediate int() cannot change the result: uint32(int(x)) == uint32(x) for
// any integer x. uint64 is excluded — it is not narrower than int.
var truncatingCast = map[string]bool{"uint8": true, "uint16": true, "uint32": true, "byte": true}

func dropDoubleCastsOnce(block string) string {
	for _, loc := range castPairPat.FindAllStringSubmatchIndex(block, -1) {
		outer, inner := block[loc[2]:loc[3]], block[loc[4]:loc[5]]
		if outer != inner && !(inner == "int" && truncatingCast[outer]) {
			continue // int(uint32(x)): a real conversion
		}
		if loc[0] > 0 && isIdentByte(block[loc[0]-1]) {
			continue // myint(myint(x)) is not a cast
		}
		match := matchParens(block)
		if match == nil {
			return block
		}
		openOuter, openInner := loc[3], loc[5] // the two '(' of the pair
		closeOuter, ok1 := match[openOuter]
		closeInner, ok2 := match[openInner]
		if !ok1 || !ok2 || closeInner != closeOuter-1 {
			// uint64(uint64(v1) << 8 | x): the inner cast covers one operand only
			continue
		}
		return block[:openOuter+1] + block[openInner+1:closeInner] + block[closeOuter:]
	}
	return block
}

var byteConstPat = regexp.MustCompile(`uint8\((\d+|0[xX][0-9a-fA-F]+)\)`)

var cmpOps = []string{"==", "!=", "<=", ">=", " < ", " > "}

// runeLiteralFor returns the character literal for a byte constant worth reading as
// text. Sizes and masks (32, 64, 0xff) are deliberately excluded: only characters
// that carry meaning in a parser are rendered as runes.
func runeLiteralFor(v int64) (string, bool) {
	if v < '0' || v > 'z' {
		return "", false
	}
	c := byte(v)
	switch {
	case c >= '0' && c <= '9', c >= 'A' && c <= 'Z', c >= 'a' && c <= 'z':
	case c == '=', c == '+', c == '/', c == '-', c == '_', c == '.', c == ',', c == ':', c == ';':
	default:
		return "", false
	}
	return "'" + string(rune(c)) + "'", true
}

// storeByteConstPat matches storing a byte constant into a slice element, as
// base64 does for its '=' padding.
var storeByteConstPat = regexp.MustCompile(`\]\s*=\s*uint8\((\d+|0[xX][0-9a-fA-F]+)\)\s*$`)

// charLiteralsForBytes rewrites uint8(110) to 'n' where the byte is being read
// or written as text: a comparison, a store into a byte slice, or a constant
// bound to a name that a comparison reads. The value is unchanged — 'n' is 110 —
// so this only decides how the number reads. Shift counts keep their numeric
// form: a rotation width is not a character.
func charLiteralsForBytes(block string) string {
	lines := strings.Split(block, "\n")
	compared := charTempsComparedTo(lines)
	for i, ln := range lines {
		hasCmp := false
		for _, op := range cmpOps {
			if strings.Contains(ln, op) {
				hasCmp = true
				break
			}
		}
		if !hasCmp && storeByteConstPat.MatchString(strings.TrimRight(ln, " \t")) {
			lines[i] = rewriteByteConsts(ln, false)
			continue
		}
		if !hasCmp {
			// A hoisted character constant — `v17 := uint8(48)` read twice, once
			// in a comparison — is still a character where it is defined.
			if lhs, ok := charTempDef(ln); ok && compared[lhs] {
				lines[i] = rewriteByteConsts(ln, true)
			}
			continue
		}
		lines[i] = rewriteByteConsts(ln, false)
	}
	return strings.Join(lines, "\n")
}

// rewriteByteConsts turns printable uint8 constants into character literals,
// leaving shift widths alone. keepWidth wraps the literal back into uint8() for
// a definition, where dropping the type would change what the name holds.
func rewriteByteConsts(ln string, keepWidth bool) string {
	return replaceAllStringSubmatchFunc(byteConstPat, ln, func(loc []int, m []string) string {
		if loc[0] >= 3 && (ln[loc[0]-3:loc[0]] == "<< " || ln[loc[0]-3:loc[0]] == ">> ") {
			return m[0]
		}
		v, err := strconv.ParseInt(strings.TrimPrefix(strings.TrimPrefix(m[1], "0x"), "0X"), base(m[1]), 64)
		if err != nil {
			return m[0]
		}
		lit, ok := runeLiteralFor(v)
		if !ok {
			return m[0]
		}
		if keepWidth {
			return "uint8(" + lit + ")"
		}
		return lit
	})
}

var charTempDefPat = regexp.MustCompile(`^\s*(v[0-9]+)\s*:?=\s*uint8\((\d+|0[xX][0-9a-fA-F]+)\)\s*$`)

// charTempDef matches a line binding a byte constant to a temporary.
func charTempDef(ln string) (string, bool) {
	sub := charTempDefPat.FindStringSubmatch(ln)
	if sub == nil {
		return "", false
	}
	return sub[1], true
}

// charTempsComparedTo collects the temporaries that a byte comparison reads, so a
// constant bound to one of them can be shown as a character too.
func charTempsComparedTo(lines []string) map[string]bool {
	out := map[string]bool{}
	for _, ln := range lines {
		if _, isDef := charTempDef(ln); isDef {
			continue
		}
		hasCmp := false
		for _, op := range cmpOps {
			if strings.Contains(ln, op) {
				hasCmp = true
				break
			}
		}
		if !hasCmp {
			continue
		}
		for _, name := range identTokens(ln) {
			out[name] = true
		}
	}
	return out
}

func base(lit string) int {
	if strings.HasPrefix(lit, "0x") || strings.HasPrefix(lit, "0X") {
		return 16
	}
	return 10
}

// replaceAllStringSubmatchFunc is regexp.ReplaceAllStringFunc with the match offsets,
// needed here to look at the two bytes preceding a match.
func replaceAllStringSubmatchFunc(re *regexp.Regexp, s string, repl func([]int, []string) string) string {
	var b strings.Builder
	last := 0
	for _, loc := range re.FindAllStringSubmatchIndex(s, -1) {
		groups := make([]string, 0, len(loc)/2)
		for i := 0; i < len(loc); i += 2 {
			if loc[i] < 0 {
				groups = append(groups, "")
				continue
			}
			groups = append(groups, s[loc[i]:loc[i+1]])
		}
		b.WriteString(s[last:loc[0]])
		b.WriteString(repl(loc, groups))
		last = loc[1]
	}
	b.WriteString(s[last:])
	return b.String()
}

// dropRedundantParens removes parens Go does not need: a fully wrapped right-hand
// side, doubled pairs, and pairs around a primary expression. Emitted expressions
// were parenthesized at every operand, which stacked up to eight levels on a
// single comparison.
func dropRedundantParens(block string) string {
	lines := strings.Split(block, "\n")
	for i, ln := range lines {
		pad := ln[:len(ln)-len(strings.TrimLeft(ln, "\t "))]
		trim := strings.TrimSpace(ln)
		if trim == "" {
			continue
		}
		if lhs, rhs, ok := splitAssign(trim); ok {
			trim = lhs + stripOuterParens(rhs)
		} else if head, cond, tail, ok := splitCond(trim); ok {
			trim = head + stripOuterParens(cond) + tail
		}
		lines[i] = pad + dropParenPairs(trim)
	}
	return strings.Join(lines, "\n")
}

// dropParenPairs deletes paren pairs that carry no grouping: a pair immediately
// wrapping another pair, or a pair around an expression with no top-level operator.
// Call and index parens — the byte before '(' is an identifier, ')' or ']' — stay.
func dropParenPairs(s string) string {
	match := matchParens(s)
	if match == nil {
		return s
	}
	drop := make([]bool, len(s))
	for i := 0; i < len(s); i++ {
		j, ok := match[i]
		if !ok {
			continue
		}
		inner := s[i+1 : j]
		doubled := len(inner) > 1 && inner[0] == '(' && match[i+1] == j-1
		if i > 0 && isCallByte(s[i-1]) {
			// f(x): these parens belong to the callee, but a lone pair inside
			// them — uint64((a - b)) — is still redundant.
			if doubled {
				drop[i+1], drop[j-1] = true, true
			}
			continue
		}
		if doubled || isPrimaryExpr(inner) {
			drop[i], drop[j] = true, true
		}
	}
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		if !drop[i] {
			b.WriteByte(s[i])
		}
	}
	return b.String()
}

func matchParens(s string) map[int]int {
	var stack []int
	out := map[int]int{}
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			stack = append(stack, i)
		case ')':
			if len(stack) == 0 {
				return nil
			}
			out[stack[len(stack)-1]] = i
			stack = stack[:len(stack)-1]
		}
	}
	if len(stack) != 0 {
		return nil
	}
	return out
}

func isCallByte(c byte) bool {
	return isIdentByte(c) || c == ')' || c == ']'
}

// isPrimaryExpr reports whether s binds tighter than any operator, so wrapping it
// in parens changes nothing: a literal, a name, a call, an index, a selector,
// optionally behind one unary prefix.
func isPrimaryExpr(s string) bool {
	if s == "" {
		return false
	}
	if c := s[0]; c == '*' || c == '^' || c == '-' || c == '&' || c == '!' {
		s = s[1:]
		if s == "" {
			return false
		}
	}
	depth := 0
	for i := 0; i < len(s); i++ {
		switch c := s[i]; c {
		case '(', '[':
			depth++
		case ')', ']':
			depth--
		case ' ', '+', '-', '*', '/', '%', '&', '|', '^', '<', '>', '=', '!', ',', ':':
			if depth == 0 {
				return false
			}
		}
	}
	return depth == 0
}

// splitAssign returns the "lhs = " / "lhs := " prefix and the right-hand side.
func splitAssign(trim string) (string, string, bool) {
	for _, sep := range []string{" := ", " = "} {
		if i := strings.Index(trim, sep); i > 0 {
			rhs := trim[i+len(sep):]
			if rhs == "" || strings.HasSuffix(rhs, "{") {
				return "", "", false
			}
			return trim[:i+len(sep)], rhs, true
		}
	}
	return "", "", false
}

// splitCond isolates the condition of an if/for header: prefix, condition, and the
// rest starting at the opening brace.
func splitCond(trim string) (string, string, string, bool) {
	var head string
	switch {
	case strings.HasPrefix(trim, "if "):
		head = "if "
	case strings.HasPrefix(trim, "for "):
		head = "for "
	case strings.HasPrefix(trim, "} else if "):
		head = "} else if "
	default:
		return "", "", "", false
	}
	depth := 0
	for i := len(head); i < len(trim); i++ {
		switch trim[i] {
		case '(':
			depth++
		case ')':
			depth--
		case '{':
			if depth == 0 {
				cond := strings.TrimSpace(trim[len(head):i])
				if cond == "" || strings.ContainsAny(cond, ";") {
					return "", "", "", false // three-clause for: leave alone
				}
				return head, cond, " " + trim[i:], true
			}
		}
	}
	return "", "", "", false
}

// stripOuterParens drops paren pairs that wrap the whole expression.
func stripOuterParens(s string) string {
	for len(s) > 1 && s[0] == '(' && s[len(s)-1] == ')' {
		depth := 0
		matched := true
		for i := 0; i < len(s); i++ {
			switch s[i] {
			case '(':
				depth++
			case ')':
				depth--
				if depth == 0 && i != len(s)-1 {
					matched = false
				}
			}
			if !matched {
				break
			}
		}
		if !matched || depth != 0 {
			return s
		}
		s = s[1 : len(s)-1]
	}
	return s
}

// typeWidth is the bit width of a scalar IR type; 0 when unknown, so an unknown
// type never wins a widening comparison.
func typeWidth(t ir.TypeName) int {
	switch t {
	case ir.TypUint8:
		return 8
	case ir.TypUint32:
		return 32
	case ir.TypUint64, ir.TypInt64, ir.TypInt:
		return 64
	}
	return 0
}

// globalsPassedToCalls names the tables that reach a function as an argument.
// Those keep a slice type: a parameter declared []byte will not take a string
// constant or a fixed-size array.
func globalsPassedToCalls(m *ir.Module) map[string]bool {
	out := map[string]bool{}
	for i := range m.Funcs {
		f := &m.Funcs[i]
		f.EnsureStmts()
		bound := map[ir.Value]string{} // register → global name
		var walk func([]ir.Stmt)
		walk = func(ss []ir.Stmt) {
			for _, s := range ss {
				switch s.Kind {
				case ir.SKInstr:
					noteGlobalUse(s.Ins, bound, out)
				case ir.SKFor:
					for _, in := range s.ForInit {
						noteGlobalUse(in, bound, out)
					}
					for _, in := range s.ForCondPrep {
						noteGlobalUse(in, bound, out)
					}
					for _, in := range s.ForPost {
						noteGlobalUse(in, bound, out)
					}
					walk(s.ForBody)
				case ir.SKSwitch:
					for _, in := range s.SwitchPrep {
						noteGlobalUse(in, bound, out)
					}
					for _, c := range s.SwitchCases {
						walk(c.Body)
					}
				case ir.SKDoWhile:
					walk(s.DoBody)
				case ir.SKIf:
					for _, in := range s.ForInit {
						noteGlobalUse(in, bound, out)
					}
					walk(s.ThenBody)
					walk(s.ElseBody)
				}
			}
		}
		walk(f.Stmts)
	}
	return out
}

func noteGlobalUse(ins ir.Instr, bound map[ir.Value]string, out map[string]bool) {
	if ins.Op == ir.OpMov && strings.HasPrefix(ins.Sym, "global:") {
		bound[ins.Dst] = sanitizeIdent(ins.Sym[len("global:"):])
		return
	}
	if ins.Op != ir.OpCall {
		return
	}
	for _, a := range ins.Args {
		if nm, ok := bound[a]; ok {
			out[nm] = true
		}
	}
}

func balanced(s string) bool {
	d := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			d++
		case ')':
			d--
			if d < 0 {
				return false
			}
		}
	}
	return d == 0
}

// foldSingleUseExprs inlines vN = EXPR when vN is read exactly once and EXPR is pure.
// Budget: each fold removes one def line, so the number of lines bounds the number
// of folds. A fixed budget starved large kernels (blake2b) and left ROT pairs split
// across a hoisted temp, blocking foldRotateExprs.
func foldSingleUseExprs(block string) string {
	// Cap budget: each once() is O(n²); blake-sized dumps must not run minutes.
	budget := strings.Count(block, "\n") + 64
	if budget > 400 {
		budget = 400
	}
	for round := 0; round < budget; round++ {
		next, n := foldSingleUseOnce(block)
		block = next
		if n == 0 {
			break
		}
	}
	return block
}

func foldSingleUseOnce(block string) (string, int) {
	lines := strings.Split(block, "\n")
	type asg struct {
		idx int
		lhs string
		rhs string
		pad string
	}
	parseAsg := func(i int, ln string) (asg, bool) {
		trim := strings.TrimSpace(ln)
		eq := strings.Index(trim, " = ")
		def := false
		if eq <= 0 {
			eq = strings.Index(trim, " := ")
			if eq <= 0 {
				return asg{}, false
			}
			def = true
		}
		sep := 3
		if def {
			sep = 4
		}
		lhs := strings.TrimSpace(trim[:eq])
		rhs := strings.TrimSpace(trim[eq+sep:])
		if !isSimpleIdent(lhs) || !strings.HasPrefix(lhs, "v") {
			return asg{}, false
		}
		if !pureExprRHS(rhs) {
			return asg{}, false
		}
		pad := ln[:len(ln)-len(strings.TrimLeft(ln, "\t "))]
		return asg{i, lhs, rhs, pad}, true
	}
	defsOf := map[string][]asg{}
	for i, ln := range lines {
		a, ok := parseAsg(i, ln)
		if !ok {
			continue
		}
		defsOf[a.lhs] = append(defsOf[a.lhs], a)
	}
	// Deterministic order: map iteration is randomized, and this pass returns after
	// the first fold, so an unordered walk made the emitted file vary run to run.
	names := make([]string, 0, len(defsOf))
	for name := range defsOf {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool {
		return defsOf[names[i]][0].idx < defsOf[names[j]][0].idx
	})
	for _, name := range names {
		defs := defsOf[name]
		if len(defs) != 1 {
			continue
		}
		d := defs[0]
		// count reads of name after def
		reads := 0
		readAt := -1
		for j := d.idx + 1; j < len(lines); j++ {
			if b, ok := parseAsg(j, lines[j]); ok && b.lhs == name {
				if identContains(b.rhs, name) {
					reads++
					readAt = j
				}
				// later def ends lifetime — but we already require single def
				continue
			}
			if identContains(lines[j], name) {
				reads++
				readAt = j
			}
		}
		if reads != 1 || readAt < 0 {
			continue
		}
		// do not inline into var decl lines
		if strings.Contains(strings.TrimSpace(lines[readAt]), "var "+name) {
			continue
		}
		// refuse if any operand of RHS is reassigned between def and use
		// (memmove: t=src[0]; src=src[1:]; dest[0]=t  must not become dest[0]=src[0] after reslice)
		if rhsReassignedBetween(lines, d.idx, readAt, d.rhs) {
			continue
		}
		// refuse if use site rebinds an operand (strchr closure: s := accept shadows outer s)
		if rhsShadowedAt(lines[readAt], d.rhs) {
			continue
		}
		// refuse inlining into for-cond if operand is mutated in loop body
		// (siphash: end=v3+inlen folded into for v3!=end → for v3!=(v3+inlen) moves bound)
		if strings.Contains(lines[readAt], "for ") && rhsAssignedAfter(lines, d.idx, d.rhs) {
			continue
		}
		// parenthesize if needed when replacing
		repl := d.rhs
		if needsParen(repl) {
			repl = "(" + repl + ")"
		}
		var out []string
		for i, ln := range lines {
			if i == d.idx {
				continue
			}
			if i == readAt {
				out = append(out, replaceIdent(ln, name, repl))
				continue
			}
			out = append(out, ln)
		}
		return strings.Join(out, "\n"), 1
	}
	return block, 0
}

func rhsReassignedBetween(lines []string, defIdx, useIdx int, rhs string) bool {
	ops := identTokens(rhs)
	for j := defIdx + 1; j < useIdx; j++ {
		trim := strings.TrimSpace(lines[j])
		if strings.HasPrefix(trim, "for _i := range ") {
			buf := strings.TrimPrefix(trim, "for _i := range ")
			if idx := strings.IndexAny(buf, " {"); idx > 0 {
				buf = buf[:idx]
			}
			for _, op := range ops {
				if op == buf {
					return true
				}
			}
		}
		eq := strings.Index(trim, " = ")
		if eq <= 0 {
			eq = strings.Index(trim, " := ")
		}
		if eq <= 0 {
			continue
		}
		lhs := strings.TrimSpace(trim[:eq])
		lhs = strings.TrimPrefix(lhs, "*")
		if br := strings.IndexByte(lhs, '['); br > 0 {
			lhs = lhs[:br]
		}
		for _, op := range ops {
			if op == lhs {
				return true
			}
		}
	}
	return false
}

func rhsShadowedAt(useLine, rhs string) bool {
	ops := identTokens(rhs)
	// crude: "name :=" anywhere in use line
	for _, op := range ops {
		if len(op) < 1 || op[0] < 'a' {
			continue // skip type names-ish / numbers
		}
		if strings.Contains(useLine, op+" :=") || strings.Contains(useLine, op+":=") {
			return true
		}
	}
	return false
}

func rhsAssignedAfter(lines []string, defIdx int, rhs string) bool {
	ops := identTokens(rhs)
	for j := defIdx + 1; j < len(lines); j++ {
		trim := strings.TrimSpace(lines[j])
		eq := strings.Index(trim, " = ")
		if eq <= 0 {
			eq = strings.Index(trim, " := ")
		}
		if eq <= 0 {
			continue
		}
		lhs := strings.TrimSpace(trim[:eq])
		lhs = strings.TrimPrefix(lhs, "*")
		if br := strings.IndexByte(lhs, '['); br > 0 {
			lhs = lhs[:br]
		}
		for _, op := range ops {
			if op == lhs {
				return true
			}
		}
	}
	return false
}

func pureExprRHS(rhs string) bool {
	if rhs == "" || strings.Contains(rhs, "\n") {
		return false
	}
	// ban statements / calls with side effects (allow bits.* and binary.* and casts)
	low := strings.ToLower(rhs)
	if strings.Contains(low, "make(") || strings.Contains(low, "append(") {
		return false
	}
	// bare call that is not bits./binary./known cast — allow math/bits and encoding/binary
	return true
}

func needsParen(expr string) bool {
	if isSimpleIdent(expr) || isIntLit(expr) {
		return false
	}
	if strings.HasPrefix(expr, "bits.") || strings.HasPrefix(expr, "binary.") {
		// bits.RotateLeft32(x, 7) is primary; bits.Foo(x) >> 1 is not
		if !strings.ContainsAny(expr, "+-*/|&^<>") {
			return false
		}
		// fall through if operators remain outside the call
	}
	// cast/call form T(...) only when the call/cast is the whole expression
	if idx := strings.IndexByte(expr, '('); idx > 0 && !strings.ContainsAny(expr[:idx], " +-*/|&^<>") {
		if match := matchParens(expr); match != nil {
			if end, ok := match[idx]; ok && end == len(expr)-1 {
				return false
			}
		}
	}
	return strings.ContainsAny(expr, " +-*/|&^<>")
}

func replaceIdent(line, name, repl string) string {
	var b strings.Builder
	i := 0
	for i < len(line) {
		if i+len(name) <= len(line) && line[i:i+len(name)] == name {
			leftOK := i == 0 || !isIdentByte(line[i-1])
			rightOK := i+len(name) == len(line) || !isIdentByte(line[i+len(name)])
			if leftOK && rightOK {
				b.WriteString(repl)
				i += len(name)
				continue
			}
		}
		b.WriteByte(line[i])
		i++
	}
	return b.String()
}

func isIdentByte(c byte) bool {
	return c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')
}

// stripDeadAssigns drops vN = EXPR (or :=) when vN is never read afterward.
func stripDeadAssigns(block string) string {
	for round := 0; round < 64; round++ {
		next, n := stripDeadAssignsOnce(block)
		block = next
		if n == 0 {
			break
		}
	}
	return block
}

func stripDeadAssignsOnce(block string) (string, int) {
	lines := strings.Split(block, "\n")
	drop := map[int]bool{}
	for i, ln := range lines {
		trim := strings.TrimSpace(ln)
		eq := strings.Index(trim, " = ")
		sep := 3
		if eq <= 0 {
			eq = strings.Index(trim, " := ")
			if eq <= 0 {
				continue
			}
			sep = 4
		}
		lhs := strings.TrimSpace(trim[:eq])
		rhs := strings.TrimSpace(trim[eq+sep:])
		if !isSimpleIdent(lhs) || !strings.HasPrefix(lhs, "v") {
			continue
		}
		_ = rhs
		// Whole-function liveness: loop-carried v4=v4+1 is used by `for v4 < n`
		// which appears *before* the assign in source order.
		// Other assigns TO lhs (v68 = …) must not count as uses — unrolled
		// clones reassign the same temp without a reader.
		used := false
		for j, other := range lines {
			if j == i || drop[j] {
				continue
			}
			ot := strings.TrimSpace(other)
			if strings.HasPrefix(ot, "var "+lhs+" ") {
				continue
			}
			// skip pure assignments to lhs (lhs = … / lhs := …)
			if eq2 := strings.Index(ot, " = "); eq2 > 0 {
				if strings.TrimSpace(ot[:eq2]) == lhs {
					// still a use if rhs reads lhs (v = v + 1)
					rhs2 := ot[eq2+3:]
					if !identContains(rhs2, lhs) {
						continue
					}
				}
			}
			if eq2 := strings.Index(ot, " := "); eq2 > 0 {
				if strings.TrimSpace(ot[:eq2]) == lhs {
					rhs2 := ot[eq2+4:]
					if !identContains(rhs2, lhs) {
						continue
					}
				}
			}
			if identContains(other, lhs) {
				used = true
				break
			}
		}
		if !used {
			drop[i] = true
		}
	}
	if len(drop) == 0 {
		return block, 0
	}
	var out []string
	for i, ln := range lines {
		if drop[i] {
			continue
		}
		out = append(out, ln)
	}
	return strings.Join(out, "\n"), len(drop)
}

// foldTempCopies: t = EXPR; v = t  (this version of t read only there) → v = EXPR; drop t def.
// Applied one fold at a time to fixpoint (batch conflicts drop vs repl on same line).
func foldTempCopies(block string) string {
	for round := 0; round < 64; round++ {
		next, n := foldTempCopiesOnce(block)
		block = next
		if n == 0 {
			break
		}
	}
	return block
}

func foldTempCopiesOnce(block string) (string, int) {
	lines := strings.Split(block, "\n")
	type asg struct {
		idx int
		lhs string
		rhs string
		pad string
	}
	parseAsg := func(i int, ln string) (asg, bool) {
		trim := strings.TrimSpace(ln)
		eq := strings.Index(trim, " = ")
		def := false
		if eq <= 0 {
			eq = strings.Index(trim, " := ")
			if eq <= 0 {
				return asg{}, false
			}
			def = true
		}
		sep := 3
		if def {
			sep = 4
		}
		lhs := strings.TrimSpace(trim[:eq])
		rhs := strings.TrimSpace(trim[eq+sep:])
		if !isSimpleIdent(lhs) || !strings.HasPrefix(lhs, "v") {
			return asg{}, false
		}
		pad := ln[:len(ln)-len(strings.TrimLeft(ln, "\t "))]
		return asg{i, lhs, rhs, pad}, true
	}
	defsOf := map[string][]asg{}
	var copies []asg
	for i, ln := range lines {
		a, ok := parseAsg(i, ln)
		if !ok {
			continue
		}
		defsOf[a.lhs] = append(defsOf[a.lhs], a)
		if isSimpleIdent(a.rhs) && strings.HasPrefix(a.rhs, "v") {
			copies = append(copies, a)
		}
	}
	for _, a := range copies {
		t := a.rhs
		// Multi-def t = mutable slot (loop index, j++ base). Folding away a
		// def of t loses updates (base64 dst[j++] → same index thrice).
		if len(defsOf[t]) != 1 {
			continue
		}
		var prior *asg
		nextIdx := len(lines)
		for i := range defsOf[t] {
			d := &defsOf[t][i]
			if d.idx < a.idx {
				prior = d
			} else if d.idx > a.idx && d.idx < nextIdx {
				nextIdx = d.idx
			}
		}
		if prior == nil {
			continue
		}
		// do not eliminate a def of t if t is still read after this copy
		// (including RHS of later "t = t + 1" — must not skip whole line on lhs==t)
		liveAfter := false
		for j := a.idx + 1; j < nextIdx; j++ {
			ln := lines[j]
			trim := strings.TrimSpace(ln)
			if strings.HasPrefix(trim, "var "+t+" ") {
				continue
			}
			if b, ok := parseAsg(j, ln); ok && b.lhs == t {
				// assignment to t: still a read if RHS mentions t
				if identContains(b.rhs, t) {
					liveAfter = true
					break
				}
				continue
			}
			if identContains(ln, t) {
				liveAfter = true
				break
			}
		}
		// also: next def of t may read t on RHS (v5 = v5 + 1)
		if !liveAfter && nextIdx < len(lines) {
			if b, ok := parseAsg(nextIdx, lines[nextIdx]); ok && b.lhs == t && identContains(b.rhs, t) {
				liveAfter = true
			}
		}
		if liveAfter {
			continue
		}
		// reads of t in (prior, nextIdx) must be exactly this copy
		reads := 0
		readAt := -1
		for j := prior.idx + 1; j < nextIdx; j++ {
			ln := lines[j]
			trim := strings.TrimSpace(ln)
			if strings.HasPrefix(trim, "var "+t+" ") {
				continue
			}
			if b, ok := parseAsg(j, ln); ok && b.lhs == t {
				if identContains(b.rhs, t) {
					reads++
					readAt = j
				}
				continue
			}
			if identContains(ln, t) {
				reads++
				readAt = j
			}
		}
		if reads != 1 || readAt != a.idx {
			continue
		}
		// apply one fold
		var out []string
		for i, ln := range lines {
			if i == prior.idx {
				continue
			}
			if i == a.idx {
				out = append(out, a.pad+a.lhs+" = "+prior.rhs)
				continue
			}
			out = append(out, ln)
		}
		return strings.Join(out, "\n"), 1
	}
	return block, 0
}

func identTokens(line string) []string {
	var out []string
	i := 0
	for i < len(line) {
		c := line[i]
		if c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') {
			j := i + 1
			for j < len(line) {
				d := line[j]
				if d == '_' || (d >= 'a' && d <= 'z') || (d >= 'A' && d <= 'Z') || (d >= '0' && d <= '9') {
					j++
					continue
				}
				break
			}
			out = append(out, line[i:j])
			i = j
			continue
		}
		i++
	}
	return out
}

// stripDeadVars removes `var vN T` lines whose name never appears in the rest of the body.
func stripDeadVars(block string) string {
	lines := strings.Split(block, "\n")
	type varLine struct {
		idx  int
		name string
	}
	var vars []varLine
	for i, ln := range lines {
		trim := strings.TrimSpace(ln)
		if !strings.HasPrefix(trim, "var ") {
			continue
		}
		// var v12 uint64
		rest := strings.TrimSpace(trim[4:])
		sp := strings.IndexByte(rest, ' ')
		if sp <= 0 {
			continue
		}
		name := rest[:sp]
		if !isSimpleIdent(name) {
			continue
		}
		vars = append(vars, varLine{i, name})
	}
	if len(vars) == 0 {
		return block
	}
	drop := map[int]bool{}
	for _, v := range vars {
		used := false
		for j, ln := range lines {
			if j == v.idx {
				continue
			}
			if strings.Contains(ln, v.name) {
				// word-boundary-ish: avoid v1 matching v12
				if identContains(ln, v.name) {
					used = true
					break
				}
			}
		}
		if !used {
			drop[v.idx] = true
		}
	}
	if len(drop) == 0 {
		return block
	}
	var out []string
	for i, ln := range lines {
		if drop[i] {
			continue
		}
		out = append(out, ln)
	}
	return strings.Join(out, "\n")
}

func identContains(line, name string) bool {
	for i := 0; i+len(name) <= len(line); i++ {
		if line[i:i+len(name)] != name {
			continue
		}
		if i > 0 {
			c := line[i-1]
			if c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') {
				continue
			}
		}
		if i+len(name) < len(line) {
			c := line[i+len(name)]
			if c == '_' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') {
				continue
			}
		}
		return true
	}
	return false
}

// canPureAlias: dst is a single-write temp copying a single-write (or named) src.
// Multi-write src needs a physical snapshot (loop-carried values).
func canPureAlias(e *env, dst ir.Value, rhs string) bool {
	if e.isParam[dst] || e.writeCount[dst] != 1 {
		return false
	}
	if !isSimpleIdent(rhs) || strings.ContainsAny(rhs, ".[]") {
		return false
	}
	if src, ok := parseVReg(rhs); ok {
		if e.writeCount[src] != 1 {
			return false
		}
	}
	return true
}

func parseVReg(s string) (ir.Value, bool) {
	if len(s) < 2 || s[0] != 'v' {
		return 0, false
	}
	n := 0
	for i := 1; i < len(s); i++ {
		c := s[i]
		if c < '0' || c > '9' {
			return 0, false
		}
		n = n*10 + int(c-'0')
	}
	return ir.Value(n), true
}

func isSimpleIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, c := range s {
		if i == 0 {
			if c != '_' && (c < 'a' || c > 'z') && (c < 'A' || c > 'Z') {
				return false
			}
			continue
		}
		if c != '_' && (c < 'a' || c > 'z') && (c < 'A' || c > 'Z') && (c < '0' || c > '9') {
			return false
		}
	}
	return true
}

