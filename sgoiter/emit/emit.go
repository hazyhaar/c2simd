func isUsedAsCond(f *ir.Func, reg ir.Value) bool {
	if reg == 0 || f == nil {
		return false
	}
	condRegs := map[ir.Value]bool{}
	var markCond func(ss []ir.Stmt)
	markCond = func(ss []ir.Stmt) {
		for _, s := range ss {
			if s.CondLeft != 0 {
				condRegs[s.CondLeft] = true
			}
			if s.CondRight != 0 {
				condRegs[s.CondRight] = true
			}
			if s.SwitchOn != 0 {
				condRegs[s.SwitchOn] = true
			}
			markCond(s.ForBody)
			markCond(s.ThenBody)
			markCond(s.ElseBody)
			for _, c := range s.SwitchCases {
				markCond(c.Body)
			}
		}
	}
	markCond(f.Stmts)

	// Propagate backwards through comparison instructions
	changed := true
	for changed {
		changed = false
		for _, ins := range f.Body {
			if strings.HasPrefix(ins.Sym, "__cmp_") && condRegs[ins.Dst] {
				for _, arg := range ins.Args {
					if arg != 0 && !condRegs[arg] {
						condRegs[arg] = true
						changed = true
					}
				}
			}
		}
	}
	return condRegs[reg]
}
